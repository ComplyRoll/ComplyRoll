@dataclass(frozen=True, slots=True)
class ReportDiagnostic:
    """One machine-readable note about a compile run."""

    level: DiagnosticLevel
    code: str
    message: str
    location: str | None = None

    def render(self) -> str:
        """Return the single-line form used on stderr."""

        text = f"{self.level.value}: {self.code}: {self.message}"
        if self.location:
            text = f"{text} [{self.location}]"
        return text

    def to_dict(self) -> dict[str, str]:
        value = {"level": self.level.value, "code": self.code, "message": self.message}
        if self.location:
            value["location"] = self.location
        return value


class ReportCompileError(Exception):
    """Compilation stopped; no report was produced."""

    def __init__(self, diagnostics: Sequence[ReportDiagnostic]) -> None:
        self.diagnostics: tuple[ReportDiagnostic, ...] = tuple(diagnostics)
        summary = "; ".join(item.message for item in self.diagnostics[:3])
        suffix = "" if len(self.diagnostics) <= 3 else f"; plus {len(self.diagnostics) - 3} more"
        super().__init__(f"report compilation failed: {summary}{suffix}")


@dataclass(frozen=True, slots=True, kw_only=True)
class ReportOptions:
    """Explicit package configuration for one compile run (Decision 5).

    The report period is optional because not every report has one (ADR 0010). The
    Vulnerability Detail Report and the Accepted Vulnerability Information report
    select by period and refuse to compile without it; the historical activity report
    is a snapshot at `as_of` and never reads it. One bound without the other is a
    mistake rather than a half-open period, so it is refused here.
    """

    certification_class: CertificationClass
    package_uri: str
    as_of: datetime
    period_from: datetime | None = None
    period_to: datetime | None = None
    calendar_timezone: str = "UTC"
    detected_at_attestation: datetime | None = None

    def __post_init__(self) -> None:
        if not isinstance(self.certification_class, CertificationClass):
            raise TypeError("certification_class must be a CertificationClass")
        _require_absolute_http_uri(self.package_uri)
        _require_aware(self.as_of, "as_of")
        if (self.period_from is None) != (self.period_to is None):
            raise ValueError("period_from and period_to must be given together")
        if self.period_from is not None and self.period_to is not None:
            _require_aware(self.period_from, "period_from")
            _require_aware(self.period_to, "period_to")
            if self.period_from > self.period_to:
                raise ValueError("period_from must not be after period_to")
        if self.detected_at_attestation is not None:
            _require_aware(self.detected_at_attestation, "detected_at_attestation")
        # Constructing the profile validates the calendar timezone at the boundary.
        CertificationProfile(
            self.certification_class,
            calendar_timezone=self.calendar_timezone,
        )

    @property
    def has_period(self) -> bool:
        """Return whether these options carry a report period."""

        return self.period_from is not None and self.period_to is not None

    @property
    def period(self) -> tuple[datetime, datetime]:
        """Return the report period as `(from, to)`, both inclusive.

        Raises `ValueError` when the options carry no period. Report projections
        that need one call `_report_period` instead, which turns the same condition
        into a compile diagnostic.
        """

        if self.period_from is None or self.period_to is None:
            raise ValueError("these options carry no report period")
        return (self.period_from, self.period_to)

    @property
    def profile(self) -> CertificationProfile:
        """Return the certification profile these options select."""

        return CertificationProfile(
            self.certification_class,
            calendar_timezone=self.calendar_timezone,
        )


@dataclass(frozen=True, slots=True)
class DetectionAttestation:
    """Attested detection times for groups whose sources declare none.

    `default` is the stateless `--detected-at` and applies to every group that needs
    one. `by_tracking_id` carries per-case attestations read back from
    `detection.attested` events and wins over the default for the cases it names. An
    attestation never overrides a detection time a source artifact declares (ADR 0007
    amendment).
    """

    default: datetime | None = None
    by_tracking_id: Mapping[str, datetime] = field(default_factory=dict)

    def for_tracking_id(self, tracking_id: str) -> datetime | None:
        """Return the instant attested for one group, or None when none applies."""

        attested = self.by_tracking_id.get(tracking_id)
        return self.default if attested is None else attested


@dataclass(frozen=True, slots=True)
class CompiledDeadline:
    """One policy clock computed for a vulnerability, with its provenance inputs."""

    rule_id: str
    rule_name: str
    force: str
    anchor: str
    start_at: datetime
    due_at: datetime
    timeframe_amount: int | str
    timeframe_unit: str
    satisfied: bool

    def to_dict(self) -> dict[str, Any]:
        # `satisfied` is the Markdown twin's Satisfied column. Publishing the clock
        # without it left a machine reader unable to tell a met deadline from a missed
        # one while a human reader of the same report could (ADR 0007 amendment, the
        # two renderings carry the same audit content).
        return {
            "ruleId": self.rule_id,
            "ruleName": self.rule_name,
            "force": self.force,
            "anchor": self.anchor,
            "startAt": _iso(self.start_at),
            "dueAt": _iso(self.due_at),
            "satisfied": self.satisfied,
            "timeframe": {"amount": self.timeframe_amount, "unit": self.timeframe_unit},
        }


