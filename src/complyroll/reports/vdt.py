"""Stateless Vulnerability Detail Report compiler (ADR 0007).

`compile_vdt_report` is a pure function of source artifacts plus explicit
operator inputs. It does not read or write the event store, so the same
artifacts, evaluations, package configuration, and `--as-of` instant produce the
same bytes on every run. It fails closed: an artifact that does not ingest, a
vulnerability with no detection time, or an evaluation that matches nothing
stops the run with diagnostics and no output.
"""

