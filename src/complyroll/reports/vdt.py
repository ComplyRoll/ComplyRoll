def compile_vdt_report(
    artifact_paths: Sequence[Path],
    *,
    options: ReportOptions,
    evaluations: EvaluationSet | None = None,
    record_failed_imports: bool = False,
) -> CompiledVdtReport:
    """Compile one Vulnerability Detail Report from artifacts and explicit inputs."""

    return project_vdt(
        compile_record_set_from_artifacts(
            artifact_paths,
            options=options,
            evaluations=evaluations,
            record_failed_imports=record_failed_imports,
        )
    )


def compile_record_set_from_artifacts(
    artifact_paths: Sequence[Path],
    *,
    options: ReportOptions,
    evaluations: EvaluationSet | None = None,
    record_failed_imports: bool = False,
) -> CompiledRecordSet:
    """Ingest artifacts, match evaluations, and compile the record set they describe.

    This is the stateless path's front half. Every report the package projects from
    the same artifacts starts here, so ingest happens once per run rather than once
    per report. With `record_failed_imports`, an artifact whose failure is mintable
    becomes a system observation instead of stopping the run (ADR 0014); without it
    every failure stops the run exactly as before. With `options.record_coverage_gaps`,
    each coverage window that closed with no verification becomes a coverage gap system
    observation, added before grouping so an evaluation finds its record (ADR 0015).
    """

    if not isinstance(options, ReportOptions):
        raise TypeError("options must be a ReportOptions")
    if evaluations is not None and not isinstance(evaluations, EvaluationSet):
        raise TypeError("evaluations must be an EvaluationSet")

    ingest_diagnostics: list[ReportDiagnostic] = []
    artifacts, observations = _ingest_all(
        artifact_paths,
        options,
        ingest_diagnostics,
        record_failed_imports=record_failed_imports,
    )
    # Derived once, from the evidence alone, before its gaps join the list; each gap is
    # ingested at the run's as-of, as every artifact and failure of this path is.
    coverage = None
    inventory = options.inventory
    if options.record_coverage_gaps and inventory is not None:
        policy = select_policy(load_bundled_rule_source_snapshot(), options.profile)
        coverage = _coverage(observations, inventory, policy, options.as_of)
        observations.extend(coverage_gap_observations(coverage, ingested_at=options.as_of))
    groups = group_open_observations(observations)
    matches = _match_evaluations(groups, evaluations)
    return compile_record_set(
        artifacts=artifacts,
        observations=observations,
        ingest_diagnostics=ingest_diagnostics,
        evaluations_by_tracking_id=matches,
        attestation=DetectionAttestation(default=options.detected_at_attestation),
        options=options,
        coverage=coverage,
        gap_aware=options.record_coverage_gaps,
    )


@dataclass(frozen=True, slots=True)
class CompiledRecordSet:
    """Every compiled vulnerability plus the shared provenance, before any report selects.

    The set knows nothing about report periods or which official format will read it.
    Each projection applies its own selection to `records` and appends its own
    diagnostics after the ones held here, so the diagnostics on the set are exactly
    the ones the compile itself raised: ingest diagnostics in their total order, then
    unresolved observations, then partial detection times in group order.
    `detection_failures` lists every detection-process system observation in the set,
    whether or not a projection's period later reports its record. `coverage` is the
    coverage projection when the options carry an inventory, and every report publishes
    it whole, since coverage is measured at as-of and never selected by a period.
    `coverage_gaps` names every coverage gap record in the set the same way, and only a
    gap-aware compile sets `coverage_gap_records`: each window of `coverage` mapped to the
    tracking id of the record carrying its gap, or None when the set holds none.
    """

    records: tuple[CompiledVulnerability, ...]
    artifacts: tuple[CompiledArtifact, ...]
    diagnostics: tuple[ReportDiagnostic, ...]
    rules_provenance: PolicyProvenance
    parser_versions: tuple[tuple[str, str], ...]
    generator_version: str
    options: ReportOptions
    detection_failures: tuple[CompiledDetectionFailure, ...] = ()
    coverage: CoverageResult | None = None
    coverage_gaps: tuple[str, ...] = ()
    coverage_gap_records: Mapping[CoverageWindow, str | None] | None = None


def compile_records(
    *,
    artifacts: Sequence[CompiledArtifact],
    observations: Sequence[Observation],
    ingest_diagnostics: Sequence[ReportDiagnostic],
    evaluations_by_tracking_id: Mapping[str, EvaluationInput],
    attestation: DetectionAttestation,
    options: ReportOptions,
) -> CompiledVdtReport:
    """Compile one report from already-normalized records.

    Both the stateless path and the event-sourced rebuild call this, so neither can
    drift from the other by construction (ADR 0008 Decision 5). Callers own how the
    artifacts, observations, ingest diagnostics, and evaluations were obtained;
    everything downstream of them happens here.

    The order a caller supplies its inputs in is not a fact about the package, so
    nothing it decides may reach the document. The stateless path receives artifacts
    and their ingest diagnostics in command-line order and the persisted path in
    ingest order, and both used to be published as given, which meant the same
    artifacts named in a different order compiled to different bytes. Both lists are
    put in a total order here, in the one place both paths run through, so the two
    paths cannot drift apart from each other or from their own earlier runs. Ordering
    them in either caller instead would fix one path and leave the other.
    """

    return project_vdt(
        compile_record_set(
            artifacts=artifacts,
            observations=observations,
            ingest_diagnostics=ingest_diagnostics,
            evaluations_by_tracking_id=evaluations_by_tracking_id,
            attestation=attestation,
            options=options,
        )
    )


def compile_record_set(
    *,
    artifacts: Sequence[CompiledArtifact],
    observations: Sequence[Observation],
    ingest_diagnostics: Sequence[ReportDiagnostic],
    evaluations_by_tracking_id: Mapping[str, EvaluationInput],
    attestation: DetectionAttestation,
    options: ReportOptions,
    coverage: CoverageResult | None = None,
    gap_aware: bool = False,
) -> CompiledRecordSet:
    """Compile the period-agnostic record set from already-normalized inputs.

    This is where the ordering guarantees `compile_records` documents are made: the
    artifact manifest and the ingest diagnostics are put in their total order here,
    on the one path both the stateless compile and the event-sourced rebuild share.
    Every report projection reads the set this returns, so a record is compiled once
    and selected many times.

    `coverage` is a projection the caller already derived from these observations, so it
    is not derived twice; it must belong to the options. With `gap_aware`, every coverage
    window is mapped to the record that carries its gap, or to None when none does, and
    each window no record carries and each gap record no window derives is named in an
    INFO note, which only a compile from history can meet (ADR 0015, divergences 1 and 2).
    """

    if not isinstance(options, ReportOptions):
        raise TypeError("options must be a ReportOptions")
    if not isinstance(attestation, DetectionAttestation):
        raise TypeError("attestation must be a DetectionAttestation")

    diagnostics: list[ReportDiagnostic] = sorted(ingest_diagnostics, key=_diagnostic_order)
    correlation = correlate_observations(observations)
    # Excluded observations are kept in the order they were read, so this block echoed
    # the caller's artifact order too. Only this list is ordered here; the diagnostics
    # raised below it follow the groups, which correlation already orders by group key.
    for observation in sorted(correlation.unresolved, key=_unresolved_order):
        diagnostics.append(
            ReportDiagnostic(
                level=DiagnosticLevel.WARNING,
                code="unresolved_observation",
                message=(
                    f"{observation.source_record_id} on "
                    f"{observation.resource.resource_id} has disposition "
                    f"{observation.disposition.value} and was not reported as a vulnerability"
                ),
                location=observation.source_artifact_name or observation.context_key,
            )
        )

    groups = correlation.groups
    snapshot = load_bundled_rule_source_snapshot()
    policy = select_policy(snapshot, options.profile)
    catalog = options.kev_catalog
    kev_rule: SelectedRule | None = None
    if catalog is not None:
        _require_kev_catalog_by_as_of(catalog, options)
        kev_rule = _kev_rule(policy, catalog)
    # Derived from the same observations on both paths, so the persisted report and the
    # stateless one carry the same block (ADR 0015).
    inventory = options.inventory
    if coverage is None:
        coverage = (
            None if inventory is None else _coverage(observations, inventory, policy, options.as_of)
        )
    elif not _coverage_belongs(coverage, inventory, policy, options):
        raise ValueError("coverage must be derived from these options' inventory, as-of and policy")
    if gap_aware and coverage is None:
        raise ValueError("a gap-aware compile needs an inventory")

    compiled: list[CompiledVulnerability] = []
    missing_detection: list[str] = []
    errors: list[ReportDiagnostic] = []
    kev_incomplete: list[CompiledVulnerability] = []
    detection_failures: list[CompiledDetectionFailure] = []
    # Each coverage gap observation's id, to the published id of the record carrying it.
    gap_tracking: dict[str, str] = {}

    for group in groups:
        detected_at, detected_source = resolve_detection_time(group, attestation)
        if detected_at is None:
            missing_detection.append(group.tracking_id)
            continue
        if detected_source == "artifact-partial":
            diagnostics.append(
                ReportDiagnostic(
                    level=DiagnosticLevel.WARNING,
                    code="detection_time_partial",
                    message=(
                        f"{group.tracking_id} groups "
                        f"{len(group.untimestamped_observation_ids)} observation(s) that "
                        "declare no source timestamp; the earliest known timestamp is the "
                        "detection time"
                    ),
                    location=group.source_record_id,
                )
            )
        evaluation = evaluations_by_tracking_id.get(group.tracking_id)
        # The order check runs before the record is built, so a record refused for both
        # reasons names its ordering error before `closed_without_disposition`. Every
        # record's errors are collected and the loop moves on, so one run names them all.
        record_errors: list[ReportDiagnostic] = []
        if evaluation is not None:
            order = evaluation_order_diagnostic(
                tracking_id=group.tracking_id,
                location=group.source_record_id,
                detected_at=detected_at,
                detected_source=detected_source,
                completed_at=evaluation.completed_at,
                source_type=group.source_type,
            )
            if order is not None and order.level is DiagnosticLevel.ERROR:
                record_errors.append(order)
            elif order is not None:
                diagnostics.append(order)
        try:
            record = _build_record(
                group=group,
                detected_at=detected_at,
                detected_at_source=detected_source,
                evaluation=evaluation,
                policy=policy,
                snapshot=snapshot,
                options=options,
                kev_rule=kev_rule,
            )
        except ReportCompileError as exc:
            record_errors.extend(exc.diagnostics)
        if record_errors:
            errors.extend(record_errors)
            continue
        compiled.append(record)
        # Only the failure type carries the metadata `_detection_failure` reads; any other
        # reserved source type is a record like any other and is never listed (ADR 0015).
        detection_failures.extend(
            _detection_failure(item, record.tracking_id)
            for item in group.observations
            if item.origin is ObservationOrigin.SYSTEM
            and item.source_type == DETECTION_FAILURE_SOURCE_TYPE
        )
        gap_tracking.update(
            (item.observation_id, record.tracking_id)
            for item in group.observations
            if item.origin is ObservationOrigin.SYSTEM
            and item.source_type == COVERAGE_GAP_SOURCE_TYPE
        )
        if kev_rule is not None and any(cve_may_be_missing(item) for item in group.observations):
            kev_incomplete.append(record)

    if missing_detection:
        errors.insert(
            0,
            ReportDiagnostic(
                level=DiagnosticLevel.ERROR,
                code="detection_time_missing",
                message=(
                    "no source timestamp and no --detected-at attestation for: "
                    + ", ".join(sorted(missing_detection))
                ),
            ),
        )
    if errors:
        raise ReportCompileError(errors)

    _require_unique_tracking_ids(compiled)
    if catalog is not None:
        diagnostics.extend(_kev_diagnostics(catalog, compiled, kev_incomplete, options))
    if coverage is not None:
        diagnostics.extend(coverage_diagnostics(coverage))
    gap_records: dict[CoverageWindow, str | None] | None = None
    if gap_aware and coverage is not None:
        window_ids = _window_gap_ids(coverage, options)
        gap_records = {window: gap_tracking.get(gap_id) for window, gap_id in window_ids.items()}
        diagnostics.extend(
            _coverage_gap_divergences(coverage, window_ids, gap_tracking, observations)
        )
    return CompiledRecordSet(
        records=tuple(compiled),
        artifacts=tuple(sorted(artifacts, key=_artifact_order)),
        diagnostics=tuple(diagnostics),
        rules_provenance=policy.provenance,
        parser_versions=_parser_versions(observations),
        generator_version=__version__,
        options=options,
        detection_failures=_ordered_detection_failures(detection_failures),
        coverage=coverage,
        coverage_gaps=tuple(sorted(set(gap_tracking.values()))),
        coverage_gap_records=gap_records,
    )


def project_vdt(record_set: CompiledRecordSet) -> CompiledVdtReport:
    """Project the Vulnerability Detail Report out of one compiled record set.

    The report period decides what is reported: accepted records are set aside for
    the VER-RPT-AVI report, and disposed records with no recorded activity in the
    period are left out, each with an INFO diagnostic appended after the set's own.
    """

    if not isinstance(record_set, CompiledRecordSet):
        raise TypeError("record_set must be a CompiledRecordSet")

    options = record_set.options
    period = _report_period(options, "the Vulnerability Detail Report")
    diagnostics = list(record_set.diagnostics)
    records, accepted, excluded = _select_for_period(record_set.records, period, diagnostics)
    attested = tuple(
        sorted(item.tracking_id for item in records if item.detected_at_source == "attestation")
    )

    metadata = ReportMetadata(
        options=options,
        artifacts=record_set.artifacts,
        rules_provenance=record_set.rules_provenance,
        schema_provenance=_schema_provenance(ReportSchema.VULNERABILITY_DETAIL),
        generator_version=record_set.generator_version,
        parser_versions=record_set.parser_versions,
        attestation_applied_to=attested,
        excluded_by_period=excluded,
        attestation_detected_at=_attested_instant(records),
        detection_failures=record_set.detection_failures,
        coverage=record_set.coverage,
        coverage_gaps=record_set.coverage_gaps,
        coverage_gap_records=record_set.coverage_gap_records,
    )
    document = _build_document(tuple(records), metadata, tuple(diagnostics))
    validation = _validate_document(ReportSchema.VULNERABILITY_DETAIL, document)
    return CompiledVdtReport(
        document=document,
        vulnerabilities=tuple(records),
        accepted=tuple(accepted),
        diagnostics=tuple(diagnostics),
        validation=validation,
        metadata=metadata,
    )


def _artifact_order(artifact: CompiledArtifact) -> tuple[str, str]:
    """Return the total order the artifact manifest is published in.

    `name` leads because it is already in every artifact record, so two runs have to
    agree on it for their documents to be byte-equal at all, and because the Markdown
    Inputs table is what a human scans by file name. `sha256` breaks the tie: two
    artifacts may carry the same name from different directories, and a report must
    not depend on which one the operator happened to name first.
    """

    return (artifact.name, artifact.sha256)


def _diagnostic_order(diagnostic: ReportDiagnostic) -> tuple[str, str, str, str]:
    """Return the total order ingest diagnostics are published in.

    Ingest diagnostics have no narrative order to preserve: each one is an independent
    note about one artifact, and the sequence they arrived in only records which file
    the caller read first. Code leads so a reader sees one kind of problem together,
    then location, then the message and level that distinguish two notes sharing both.
    """

    return (
        diagnostic.code,
        diagnostic.location or "",
        diagnostic.message,
        diagnostic.level.value,
    )


def _unresolved_order(observation: Observation) -> tuple[str, str, str, str, str]:
    """Return the total order unresolved observations are reported in.

    The fields are the ones the diagnostic renders (its location, then the record,
    resource, and disposition its message names), so the published order is the order
    a reader would sort the printed lines into. `observation_id` is last and is a
    content fingerprint, so the order is total even where every rendered field agrees.
    """

    return (
        observation.source_artifact_name or observation.context_key,
        observation.source_record_id,
        observation.resource.resource_id,
        observation.disposition.value,
        observation.observation_id,
    )


#: One reading of an artifact and, when failed imports are recorded, how it failed.
_Reading = tuple[IngestResult, FailureClassification | None]


def _ingest_all(
    artifact_paths: Sequence[Path],
    options: ReportOptions,
    diagnostics: list[ReportDiagnostic],
    *,
    record_failed_imports: bool = False,
) -> tuple[list[CompiledArtifact], list[Observation]]:
    if not artifact_paths:
        raise ReportCompileError(
            (
                ReportDiagnostic(
                    level=DiagnosticLevel.ERROR,
                    code="no_artifacts",
                    message="at least one source artifact is required",
                ),
            )
        )

    errors: list[ReportDiagnostic] = []
    by_digest: dict[str, list[_Reading]] = {}
    # Mintable failures by digest, none of whose diagnostics are appended yet: whether a
    # failure contributes its own or `failure_diagnostics` depends on whether the same
    # bytes read successfully elsewhere in the run, which is known only after the loop.
    held: dict[str, list[tuple[IngestResult, FailureClassification]]] = {}

    for raw_path in artifact_paths:
        path = Path(raw_path)
        result = ingest_stig_artifact(path, ingested_at=options.as_of)
        classification = classify_ingest(result) if record_failed_imports else None
        if result.errors and classification is not None and classification.mintable:
            held.setdefault(_require_artifact(result).digest_sha256, []).append(
                (result, classification)
            )
            continue
        _collect_diagnostics(result, path.name, diagnostics, errors)
        if result.errors or result.artifact is None:
            continue
        by_digest.setdefault(result.artifact.digest_sha256, []).append((result, classification))

    failed: dict[str, list[tuple[IngestResult, FailureClassification]]] = {}
    for digest, readings in held.items():
        for result, classification in readings:
            # Bytes that read successfully under another name are a misnamed copy, not a
            # failed detection, so the reading stops the run exactly as it always has.
            if digest in by_digest:
                classification = classification.read_elsewhere()
            if classification.mintable:
                failed.setdefault(digest, []).append((result, classification))
            else:
                _collect_diagnostics(result, _require_artifact(result).name, diagnostics, errors)

    if errors:
        # The run stops, so nothing is recorded: every held failure names itself with its
        # own ERRORs, exactly as the run would without the flag.
        for readings in failed.values():
            for result, _ in readings:
                _collect_diagnostics(result, _require_artifact(result).name, diagnostics, errors)
        raise ReportCompileError(sorted(errors, key=_diagnostic_order))

    artifacts: list[CompiledArtifact] = []
    observations: list[Observation] = []
    # By elected name, which is the order the manifest is published in. Nothing
    # downstream reads the observation list in order (correlation orders each group's
    # members and sorts what it excludes), so this loop decides no output on its own;
    # walking it in the published order keeps that true of what a reader sees here too.
    elected = sorted(
        (_elect_reading(group) for group in by_digest.values()),
        key=lambda item: (item[0].artifact.name, item[0].artifact.digest_sha256),
    )
    for read, skipped in elected:
        _warn_duplicates(read, skipped, diagnostics)
        artifacts.append(
            CompiledArtifact(
                name=read.artifact.name,
                sha256=read.artifact.digest_sha256,
                parser=read.artifact.parser_name,
                parser_version=read.artifact.parser_version,
                size_bytes=read.artifact.size_bytes,
                observation_count=len(read.observations),
            )
        )
        observations.extend(read.observations)
        # Only a side record reaches here classified: its artifact imports as it always
        # has, and the failed invocation is recorded beside it.
        _record_detection_failure(read, options, diagnostics, observations)

    # A failed artifact is not in the manifest, which lists what was read; its system
    # observation's metadata becomes its entry in `detectionFailures` instead.
    for read, skipped in sorted(
        (_elect_reading(group) for group in failed.values()),
        key=lambda item: (item[0].artifact.name, item[0].artifact.digest_sha256),
    ):
        _warn_duplicates(read, skipped, diagnostics)
        _record_detection_failure(read, options, diagnostics, observations)

    return artifacts, observations


def _collect_diagnostics(
    result: IngestResult,
    name: str,
    diagnostics: list[ReportDiagnostic],
    errors: list[ReportDiagnostic],
) -> None:
    """Append one reading's diagnostics: ERRORs to `errors`, the rest to `diagnostics`."""

    for item in result.diagnostics:
        entry = ReportDiagnostic(
            level=item.level,
            code=item.code,
            message=item.message,
            # The artifact name, never the supplied path: diagnostics are embedded in
            # the report, which must not depend on the caller's directory layout.
            location=item.location or name,
        )
        if item.level is DiagnosticLevel.ERROR:
            errors.append(entry)
        else:
            diagnostics.append(entry)


def _warn_duplicates(
    read: _ElectedReading,
    skipped: Sequence[ArtifactProvenance],
    diagnostics: list[ReportDiagnostic],
) -> None:
    """Note each reading of the elected reading's bytes that the report does not carry.

    Both names are file names the operator supplied, so they pass through `diagnostic_text`,
    as the adapters' diagnostic paths and the failure diagnostics do, before the report
    embeds them.
    """

    elected = diagnostic_text(read.artifact.name)
    for duplicate in skipped:
        diagnostics.append(
            ReportDiagnostic(
                level=DiagnosticLevel.WARNING,
                code="duplicate_artifact",
                message=(
                    "identical artifact bytes were supplied more than once; this "
                    f"report reads them as {elected}"
                ),
                location=diagnostic_text(duplicate.name),
            )
        )


def _record_detection_failure(
    read: _ElectedReading,
    options: ReportOptions,
    diagnostics: list[ReportDiagnostic],
    observations: list[Observation],
) -> None:
    """Mint the system observation of one elected reading's failure, if it has one.

    A failed reading contributes `failure_diagnostics` in place of its own diagnostics,
    with every ERROR demoted, and a side record contributes only its one
    `detection_failure_recorded` WARNING. The instant is the run's as-of, the moment
    ComplyRoll saw the failure, unless the scanner declared the failed invocation's own
    clock. It is never clamped to the report period (ADR 0014).
    """

    classification = read.classification
    if classification is None:
        return
    name = read.artifact.name
    for item in failure_diagnostics(read.result, classification, name=name):
        diagnostics.append(
            ReportDiagnostic(
                level=item.level,
                code=item.code,
                message=item.message,
                location=item.location,
            )
        )
    observations.append(
        system_observation_for(read.result, classification, name=name, observed_at=options.as_of)
    )


@dataclass(frozen=True, slots=True)
class _ElectedReading:
    """The one reading of a set of identical artifact bytes that the report carries.

    `result` and `classification` are the reading as ingested and, when failed imports
    are recorded, how it failed; a clean reading, or any reading of a run that records
    no failures, has no classification.
    """

    artifact: ArtifactProvenance
    observations: tuple[Observation, ...]
    result: IngestResult
    classification: FailureClassification | None


def _elect_reading(
    candidates: Sequence[_Reading],
) -> tuple[_ElectedReading, tuple[ArtifactProvenance, ...]]:
    """Choose which of several readings of one artifact's bytes the report carries.

    The same bytes may be supplied twice under different file names, and only one
    reading can be in the report: the observations of the second would restate every
    finding of the first under the same fingerprints. Keeping whichever arrived first
    made the manifest name, and the name every observation carries, depend on the
    order the operator listed the files in. Electing the lowest name instead makes the
    choice a property of the file set. Two candidates that share a name also share
    their bytes, so every field either could contribute is identical and which one is
    elected is not observable. Failed readings of one digest are elected the same way,
    so one failure is recorded however many names its bytes were supplied under.
    """

    readings = sorted(
        (
            _ElectedReading(_require_artifact(item), item.observations, item, classification)
            for item, classification in candidates
        ),
        key=lambda item: item.artifact.name,
    )
    read, *rest = readings
    return read, tuple(item.artifact for item in rest)


def _require_artifact(result: IngestResult) -> ArtifactProvenance:
    """Return one candidate's artifact, which `_ingest_all` has already checked for.

    A mintable failure always carries one, because a reading with no digest is refused.
    """

    artifact = result.artifact
    if artifact is None:  # pragma: no cover - candidates are filtered before election
        raise AssertionError("a candidate reading must carry an artifact")
    return artifact


def _match_evaluations(
    groups: Sequence[VulnerabilityGroup],
    evaluations: EvaluationSet | None,
) -> dict[str, EvaluationInput]:
    if evaluations is None or not evaluations.entries:
        return {}
    matched: dict[str, EvaluationInput] = {}
    claimed_by: dict[str, EvaluationInput] = {}
    errors: list[ReportDiagnostic] = []

    for entry in evaluations.entries:
        candidates = [group for group in groups if _matches(entry, group)]
        if not candidates:
            errors.append(
                ReportDiagnostic(
                    level=DiagnosticLevel.ERROR,
                    code="evaluation_unmatched",
                    message=f"no vulnerability matches {entry.match.describe()}",
                    location=entry.location,
                )
            )
            continue
        if len(candidates) > 1:
            named = ", ".join(group.tracking_id for group in candidates)
            errors.append(
                ReportDiagnostic(
                    level=DiagnosticLevel.ERROR,
                    code="evaluation_ambiguous",
                    message=(
                        f"{entry.match.describe()} matches {len(candidates)} vulnerabilities "
                        f"({named}); {entry.match.ambiguity_remedy()}"
                    ),
                    location=entry.location,
                )
            )
            continue
        group = candidates[0]
        # A lone system record would match an entry short of the full triple, so the next
        # record of another key, or an artifact record of the same key, would turn the same
        # file ambiguous; every reserved source type needs the triple (ADR 0014 Decision 10,
        # ADR 0015 Decision 23).
        if group.source_type.startswith(RESERVED_SOURCE_TYPE_PREFIX) and (
            entry.match.context_key is None or entry.match.source_type is None
        ):
            errors.append(
                ReportDiagnostic(
                    level=DiagnosticLevel.ERROR,
                    code="evaluation_context_key_required",
                    message=entry.match.context_key_required(
                        group.tracking_id, kind=system_record_kind(group.source_type)
                    ),
                    location=entry.location,
                )
            )
            continue
        previous = claimed_by.get(group.tracking_id)
        if previous is not None:
            errors.append(
                ReportDiagnostic(
                    level=DiagnosticLevel.ERROR,
                    code="evaluation_duplicate",
                    message=(
                        f"{group.tracking_id} is evaluated by both {previous.location} "
                        f"and {entry.location}"
                    ),
                    location=entry.location,
                )
            )
            continue
        claimed_by[group.tracking_id] = entry
        matched[group.tracking_id] = entry

    if errors:
        raise ReportCompileError(errors)
    return matched


#: How a refusal names the record of each reserved source type (ADR 0015).
_SYSTEM_RECORD_KINDS = {
    DETECTION_FAILURE_SOURCE_TYPE: "detection process failure",
    COVERAGE_GAP_SOURCE_TYPE: "coverage gap",
}


def system_record_kind(source_type: str) -> str:
    """Name the record of one reserved source type, or "system record" for any other.

    `reports.vdt` and `history.writers` name a refusal with it, so both paths agree.
    """

    return _SYSTEM_RECORD_KINDS.get(source_type, "system record")


def _matches(entry: EvaluationInput, group: VulnerabilityGroup) -> bool:
    if entry.match.source_record_id != group.source_record_id:
        return False
    if entry.match.context_key is not None and entry.match.context_key != group.context_key:
        return False
    return not (
        entry.match.source_type is not None and entry.match.source_type != group.source_type
    )


def resolve_detection_time(
    group: VulnerabilityGroup,
    attestation: DetectionAttestation,
) -> tuple[datetime | None, str]:
    """Resolve one group's detection time without ever guessing one.

    A supplied attestation applies only to groups where no observation declares a
    source timestamp; it never overrides a known one (ADR 0007 amendment). A detection
    process failure is checked first: it is timed by the instant it was recorded, is
    never attested, and never reads as a source artifact's timestamp (ADR 0014).

    The source is `system`, `artifact`, `artifact-partial`, `attestation`, or
    `missing` with no instant. It is public so the history writers resolve a case's
    detection time exactly as a report from the store does.
    """

    observed_at = group.earliest_observed_at
    if observed_at is not None and _is_system_group(group):
        return observed_at.astimezone(UTC), "system"
    if group.earliest_observed_at is not None:
        source = "artifact-partial" if group.has_partial_timestamps else "artifact"
        return group.earliest_observed_at.astimezone(UTC), source
    attested = attestation.for_tracking_id(group.tracking_id)
    if attested is not None:
        return attested.astimezone(UTC), "attestation"
    return None, "missing"


#: The remedy a refusal names, by the source of the detection time it is refused against.
#: The compiler, the history writers and `store verify` print one text per source, and
#: per source type for `system`, so each must hold on both paths (ADR 0007 amendment
#: 2026-10-14). The `system` text is a detection process failure's; a type may name its own.
_ORDER_REMEDIES = {
    "artifact": "supply the artifact that detected it earlier, or correct completedAt",
    "attestation": "attest an earlier detection time, or correct completedAt",
    "system": (
        "a detection process failure is detected when it is recorded, at the ingest "
        "--as-of in history and at the run's as-of on the stateless path, so evaluate it "
        "at or after that instant, correct completedAt, or on the stateless path report "
        "with an --as-of no later than completedAt"
    ),
}
#: A system record whose detection time is fixed by its inputs on both paths names no
#: as-of remedy (ADR 0015).
_SYSTEM_ORDER_REMEDIES = {
    COVERAGE_GAP_SOURCE_TYPE: (
        "a coverage gap is detected when its window closed, so evaluate it at or after that "
        "instant, or correct completedAt"
    ),
}


def evaluation_order_diagnostic(
    *,
    tracking_id: str,
    location: str,
    detected_at: datetime,
    detected_source: str,
    completed_at: datetime,
    source_type: str | None = None,
) -> ReportDiagnostic | None:
    """Order one evaluation's `completedAt` against its record's detection time.

    An evaluation completed strictly before a detection time that is the record's own
    (`artifact`, `attestation` or `system`) is the ERROR `evaluation_before_detection`;
    one completed at the detection instant is in order. A partly timestamped group's
    detection time is only the earliest known timestamp, and an observation declaring
    none may have detected it earlier, so it gets the WARNING
    `evaluation_before_partial_detection` and the record is published. Only
    `completedAt` is ordered: a reduction or a projection starts no clock. For a
    `system` detection time, the record's `source_type` chooses the remedy.
    """

    completed = completed_at.astimezone(UTC)
    detected = detected_at.astimezone(UTC)
    if completed >= detected:
        return None
    if detected_source == "artifact-partial":
        return ReportDiagnostic(
            level=DiagnosticLevel.WARNING,
            code="evaluation_before_partial_detection",
            message=(
                f"{tracking_id} was evaluated at {_iso(completed)}, before its earliest known "
                f"detection time {_iso(detected)} (source artifact-partial); an observation "
                "that declares no source timestamp may have detected it earlier, so the "
                "record is published"
            ),
            location=location,
        )
    remedy = _ORDER_REMEDIES.get(detected_source)
    if detected_source == "system" and source_type is not None:
        remedy = _SYSTEM_ORDER_REMEDIES.get(source_type, remedy)
    if remedy is None:
        return None
    return ReportDiagnostic(
        level=DiagnosticLevel.ERROR,
        code="evaluation_before_detection",
        message=(
            f"{tracking_id} was evaluated at {_iso(completed)}, before its detection time "
            f"{_iso(detected)} (source {detected_source}); {remedy}"
        ),
        location=location,
    )


def _is_system_group(group: VulnerabilityGroup) -> bool:
    """Return True for a group of system observations, which never shares a key with others.

    Only a system observation may carry the reserved detection-process source type, so a
    group key never mixes the two origins.
    """

    return all(item.origin is ObservationOrigin.SYSTEM for item in group.observations)


def _detection_failure(observation: Observation, tracking_id: str) -> CompiledDetectionFailure:
    """Describe one detection-process observation for `detectionFailures`, from its metadata."""

    metadata = dict(observation.source_metadata)
    observed_at = observation.observed_at
    if observed_at is None:  # pragma: no cover - a system observation is always timed
        raise AssertionError("a system observation must carry observed_at")
    return CompiledDetectionFailure(
        name=metadata["artifact.name"],
        sha256=metadata["artifact.sha256"],
        size_bytes=int(metadata["artifact.sizeBytes"]),
        parser=metadata["artifact.parser"],
        parser_version=metadata["artifact.parserVersion"],
        failure_class=metadata["failure.class"],
        failure_codes=tuple(json.loads(metadata["failure.codes"])),
        observed_at=observed_at.astimezone(UTC),
        clock=metadata["failure.clock"],
        tracking_id=tracking_id,
    )


def _ordered_detection_failures(
    failures: Sequence[CompiledDetectionFailure],
) -> tuple[CompiledDetectionFailure, ...]:
    """Put `detectionFailures` in its total order: name, sha256, parser, version, instant.

    The persisted path can hold several current failures of one digest, differing in
    parser, version or instant, so the order must reach past the digest. Parser versions
    compare by the rule `history.fold._newest_stream` applies, reproduced here because
    this module cannot import the history package: when every version of a digest is
    dot-separated ASCII digits they compare as numbers with trailing zero components
    dropped, so 10 follows 9 and 1.0 ties 1, and otherwise the digest's versions compare
    as text. The version as written breaks the last tie, so the order is total.
    """

    numeric: dict[str, bool] = {}
    for item in failures:
        numeric[item.sha256] = numeric.get(item.sha256, True) and _is_numeric_version(
            item.parser_version
        )

    def key(
        item: CompiledDetectionFailure,
    ) -> tuple[str, str, str, tuple[int, ...], str, datetime, str]:
        number: tuple[int, ...] = ()
        text = item.parser_version
        if numeric[item.sha256]:
            number, text = _numeric_version(item.parser_version), ""
        return (
            item.name,
            item.sha256,
            item.parser,
            number,
            text,
            item.observed_at,
            item.parser_version,
        )

    return tuple(sorted(failures, key=key))


def _is_numeric_version(version: str) -> bool:
    """Return True when every dot-separated component is ASCII digits `int` can read.

    The same test as `history.fold._is_numeric_version`, so U+00B2 and U+2460, which
    `str.isdigit` accepts and `int` refuses, fall to the text comparison.
    """

    parts = version.split(".")
    return bool(parts) and all(part.isascii() and part.isdigit() for part in parts)


def _numeric_version(version: str) -> tuple[int, ...]:
    """Return the tuple one numeric parser version compares as, trailing zeros dropped."""

    parts = [int(part) for part in version.split(".")]
    while len(parts) > 1 and parts[-1] == 0:
        parts.pop()
    return tuple(parts)


def _attested_instant(records: Sequence[CompiledVulnerability]) -> datetime | None:
    """Return the one instant every attested record shares, or None if they differ.

    The instant is read off the record, never looked up again by identifier. An
    operator's `trackingId` override renames a record after its detection time is
    resolved, so `record.tracking_id` is no longer a key into the attestation map
    while `record.original_tracking_id` is; resolving the shared instant from the
    resolved records leaves no key to get wrong. `_attestation_groups` reads the same
    field, so the scalar form and the grouped form describe one set of facts.
    """

    instants = {
        record.detected_at for record in records if record.detected_at_source == "attestation"
    }
    if len(instants) != 1:
        return None
    return next(iter(instants))


def _attestation_groups(
    records: Sequence[CompiledVulnerability],
) -> tuple[tuple[datetime, tuple[str, ...]], ...]:
    """Group the attested records by the instant attested for each, earliest first.

    Both renderings read this, so the JSON block and the Markdown twin can never
    describe different groupings of the same records.
    """

    grouped: dict[datetime, list[str]] = {}
    for record in records:
        if record.detected_at_source != "attestation":
            continue
        grouped.setdefault(record.detected_at, []).append(record.tracking_id)
    return tuple(
        (instant, tuple(sorted(tracking_ids))) for instant, tracking_ids in sorted(grouped.items())
    )


def _require_unique_tracking_ids(records: Sequence[CompiledVulnerability]) -> None:
    """Refuse a trackingId override that would merge two vulnerabilities.

    An override may rename one vulnerability; it may not collapse two into one
    (ADR 0007 amendment).
    """

    claimed: dict[str, CompiledVulnerability] = {}
    collisions: list[ReportDiagnostic] = []
    for record in records:
        previous = claimed.get(record.tracking_id)
        if previous is None:
            claimed[record.tracking_id] = record
            continue
        collisions.append(
            ReportDiagnostic(
                level=DiagnosticLevel.ERROR,
                code="tracking_id_collision",
                message=(
                    f"effective tracking id {record.tracking_id!r} is claimed by "
                    f"{previous.evaluation_location} (originally "
                    f"{previous.original_tracking_id}) and {record.evaluation_location} "
                    f"(originally {record.original_tracking_id}); an override may rename "
                    "one vulnerability but may not merge two"
                ),
                location=record.evaluation_location,
            )
        )
    if collisions:
        raise ReportCompileError(collisions)


def _require_kev_catalog_by_as_of(catalog: KevCatalog, options: ReportOptions) -> None:
    """Refuse a CISA KEV catalog released after `as_of` (ADR 0012 Decision 6).

    Entries change after publication, so a later catalog cannot show that the due date
    it carries was in force at `as_of`. Regenerating an old report needs the catalog
    that was current then, and the old report's `kevSource` names its digest.
    """

    if catalog.date_released <= options.as_of:
        return
    raise ReportCompileError(
        (
            ReportDiagnostic(
                level=DiagnosticLevel.ERROR,
                code="kev_catalog_after_as_of",
                message=(
                    f"the CISA KEV catalog was released {_iso(catalog.date_released)}, "
                    f"after as_of {_iso(options.as_of)}; a later catalog cannot show which "
                    "due dates were in force at as_of, so supply the catalog current then"
                ),
                location=_kev_location(catalog),
            ),
        )
    )


def _kev_rule(policy: SelectedPolicy, catalog: KevCatalog) -> SelectedRule:
    """Return the selected VDR-TFR-KEV rule, or stop the run when the policy lacks it.

    Only a run with a catalog asks, so a run without one never needs the rule. The
    refusal is a catalog-level note like every other one that is not per record, so it
    is located by the catalog digest rather than by a record id (ADR 0012).
    """

    try:
        return policy.rule(_KEV_RULE)
    except PolicyRuleNotFoundError as exc:
        raise ReportCompileError(
            (
                ReportDiagnostic(
                    level=DiagnosticLevel.ERROR,
                    code="kev_rule_unavailable",
                    message=(
                        "a CISA KEV catalog was supplied, but the Class "
                        f"{policy.profile.certification_class.value} policy selects no "
                        f"{_KEV_RULE} rule, so no KEV clock can run"
                    ),
                    location=_kev_location(catalog),
                ),
            )
        ) from exc


def _kev_diagnostics(
    catalog: KevCatalog,
    records: Sequence[CompiledVulnerability],
    incomplete: Sequence[CompiledVulnerability],
    options: ReportOptions,
) -> list[ReportDiagnostic]:
    """Return the catalog-level KEV notes, then the per-record ones, in their fixed order.

    Catalog-level notes are located by the catalog digest and never name the file, so
    the same bytes under another path raise the same notes (ADR 0012). `incomplete` is
    in record order, and so are the per-record notes.
    """

    location = _kev_location(catalog)
    as_of_date = options.as_of.astimezone(UTC).date()
    notes: list[ReportDiagnostic] = []

    if options.as_of - catalog.date_released > KEV_STALE_AFTER:
        notes.append(
            ReportDiagnostic(
                level=DiagnosticLevel.WARNING,
                code="kev_catalog_stale",
                message=(
                    f"the CISA KEV catalog was released {_iso(catalog.date_released)}, more "
                    f"than {KEV_STALE_AFTER.days} days before as_of {_iso(options.as_of)}; "
                    "entries CISA added since its release are not applied"
                ),
                location=location,
            )
        )

    later = frozenset(entry.cve_id for entry in catalog.entries if entry.date_added > as_of_date)
    if later:
        carrying = sum(1 for record in records if later.intersection(record.source_identifiers))
        entries = "1 catalog entry" if len(later) == 1 else f"{len(later)} catalog entries"
        verb = "was" if len(later) == 1 else "were"
        notes.append(
            ReportDiagnostic(
                level=DiagnosticLevel.INFO,
                code="kev_entries_after_as_of",
                message=(
                    f"{entries} dated after {as_of_date.isoformat()} {verb} not applied; "
                    f"{_records_carry(carrying)} {'it' if len(later) == 1 else 'one of them'}"
                ),
                location=location,
            )
        )

    with_cve = sum(
        1
        for record in records
        if any(identifier.startswith(_CVE_PREFIX) for identifier in record.source_identifiers)
    )
    if not with_cve:
        notes.append(
            ReportDiagnostic(
                level=DiagnosticLevel.INFO,
                code="kev_no_cve_identifiers",
                message=(
                    "a CISA KEV catalog was supplied, but no compiled record carries a CVE "
                    "identifier, so no entry could match"
                ),
                location=location,
            )
        )
    elif not any(record.kev is not None for record in records):
        notes.append(
            ReportDiagnostic(
                level=DiagnosticLevel.INFO,
                code="kev_no_matches",
                message=(
                    f"{_records_carry(with_cve)} CVE identifiers, and none matched a CISA "
                    f"KEV catalog entry dated on or before {as_of_date.isoformat()}"
                ),
                location=location,
            )
        )

    for record in incomplete:
        notes.append(
            ReportDiagnostic(
                level=DiagnosticLevel.WARNING,
                code="kev_match_incomplete",
                message=(
                    f"{record.tracking_id} groups an observation whose source identifiers "
                    "were cut at the adapter's limit, and a CVE may be among those dropped, "
                    "so a CISA KEV entry for it cannot be matched"
                ),
                location=record.source_record_id,
            )
        )
    return notes


def _kev_location(catalog: KevCatalog) -> str:
    return f"sha256:{catalog.sha256}"


def derive_report_coverage(
    observations: Sequence[Observation],
    inventory: Inventory,
    profile: CertificationProfile,
    as_of: datetime,
) -> CoverageResult:
    """Derive the coverage block a report of these inputs carries, as the report derives it.

    `cases coverage` records the gaps of exactly this projection (ADR 0015): the policy the
    profile selects from the pinned dataset, the same refusal when it lacks a coverage
    rule, and a derivation that never reads a system observation as evidence.
    """

    if not isinstance(inventory, Inventory):
        raise TypeError("inventory must be an Inventory")
    if not isinstance(profile, CertificationProfile):
        raise TypeError("profile must be a CertificationProfile")
    _require_aware(as_of, "as_of")
    policy = select_policy(load_bundled_rule_source_snapshot(), profile)
    return _coverage(observations, inventory, policy, as_of)


def _coverage(
    observations: Sequence[Observation],
    inventory: Inventory,
    policy: SelectedPolicy,
    as_of: datetime,
) -> CoverageResult:
    """Return the coverage projection, or stop the run when the policy lacks a coverage rule.

    Only a run with an inventory asks, so a run without one never needs the five rules
    (ADR 0015). Every rule the policy lacks is named in one note, located at the
    inventory's name like every other note about the inventory as a whole.
    """

    missing = [rule_id for rule_id in COVERAGE_RULE_IDS if not _selects(policy, rule_id)]
    if missing:
        raise ReportCompileError(
            (
                ReportDiagnostic(
                    level=DiagnosticLevel.ERROR,
                    code="coverage_rule_unavailable",
                    message=(
                        "an information resource inventory was supplied, but the Class "
                        f"{policy.profile.certification_class.value} policy selects no "
                        f"{', '.join(missing)} rule, so no coverage clock can run"
                    ),
                    location=inventory.name,
                ),
            )
        )
    return derive_coverage(observations, inventory, policy, as_of)


def _selects(policy: SelectedPolicy, rule_id: str) -> bool:
    try:
        policy.rule(rule_id)
    except PolicyRuleNotFoundError:
        return False
    return True


def _coverage_belongs(
    coverage: CoverageResult,
    inventory: Inventory | None,
    policy: SelectedPolicy,
    options: ReportOptions,
) -> bool:
    """Return whether a handed projection was derived from these options and policy."""

    return (
        inventory is not None
        and coverage.inventory == inventory
        and coverage.as_of == options.as_of
        and coverage.profile == policy.profile
        and coverage.provenance == policy.provenance
    )


def _window_gap_ids(coverage: CoverageResult, options: ReportOptions) -> dict[CoverageWindow, str]:
    """Return the id of each window's gap, rebuilt from the window alone.

    The id depends only on the window, never on the ingest time, so rebuilding the gap
    here names the observation whichever path recorded it.
    """

    return {
        window: coverage_gap_observation(
            window, inventory=coverage.inventory, ingested_at=options.as_of
        ).observation_id
        for window in coverage.windows
    }


def _coverage_gap_divergences(
    coverage: CoverageResult,
    window_ids: Mapping[CoverageWindow, str],
    gap_tracking: Mapping[str, str],
    observations: Sequence[Observation],
) -> list[ReportDiagnostic]:
    """Name each window no gap record carries, then each gap record no window derives.

    A stateless run records every window it derives and nothing else, so only a compile
    from history meets either (ADR 0015, divergences 1 and 2). A missed window is a
    permanent fact: a gap this run no longer derives keeps its case, and the note says why,
    as `coverage_gap_contradicted` when evidence inside the window disproves it and as
    `coverage_gap_unmatched` when none does. A disposition answers a whole case, so each
    note is read against the other recorded gaps of its case as well.
    """

    notes: list[ReportDiagnostic] = []
    for window, gap_id in window_ids.items():
        if gap_id in gap_tracking:
            continue
        label = _coverage_label(window.key.subject)
        notes.append(
            ReportDiagnostic(
                level=DiagnosticLevel.INFO,
                code="coverage_gap_unrecorded",
                message=(
                    f"the {window.rule_id} window for {label} closed {_iso(window.closed_at)} "
                    "with no verification, and history records no gap for it, so no case in "
                    "this report carries it; cases coverage with this run's inventory, as-of, "
                    "class and calendar zone records it"
                ),
                location=f"{coverage.inventory.name} {label}",
            )
        )
    derived = set(window_ids.values())
    recorded = sorted(
        (
            item
            for item in observations
            if item.origin is ObservationOrigin.SYSTEM
            and item.source_type == COVERAGE_GAP_SOURCE_TYPE
            and item.observation_id in gap_tracking
        ),
        key=_gap_order,
    )
    disproof = {
        item.observation_id: _disproving_evidence(item, observations, coverage)
        for item in recorded
        if item.observation_id not in derived
    }
    # Each case's recorded gaps, in window order, so siblings are found once per case.
    cases: dict[str, list[Observation]] = {}
    for item in recorded:
        cases.setdefault(gap_tracking[item.observation_id], []).append(item)
    for item in recorded:
        if item.observation_id not in disproof:
            continue
        tracking_id = gap_tracking[item.observation_id]
        siblings = [other for other in cases[tracking_id] if other is not item]
        # A sibling still derived, or one nothing disproves, keeps the case open.
        standing = [
            (other, other.observation_id in derived)
            for other in siblings
            if other.observation_id in derived or disproof[other.observation_id] is None
        ]
        notes.append(
            _underived_gap(
                item,
                tracking_id,
                disproof[item.observation_id],
                standing=standing,
                shared=bool(siblings),
            )
        )
    return notes


def _disproving_evidence(
    gap: Observation, observations: Sequence[Observation], coverage: CoverageResult
) -> CoverageEvidence | None:
    """Return the earliest verification inside a recorded gap's window, or None.

    The window is (anchorAt, windowClosedAt] from the record's own metadata, which the
    reader holds to its head and its close to the instant it is observed at. Evidence is
    filed as the derivation files it, so a verification after this run's as-of is not used.
    """

    closed_at = gap.observed_at
    if closed_at is None:  # pragma: no cover - a gap is always observed at its window close
        raise ValueError(f"coverage gap {gap.observation_id} has no window close")
    rule = gap.context_key.split(":", 1)[0]
    anchor_at = datetime.fromisoformat(dict(gap.source_metadata)["coverage.anchorAt"])
    return next(
        (
            item
            for item in verifying_evidence(
                observations, coverage.inventory, coverage.as_of, rule_id=rule, subject=gap.resource
            )
            if item.at is not None and anchor_at < item.at <= closed_at
        ),
        None,
    )


def _underived_gap(
    gap: Observation,
    tracking_id: str,
    evidence: CoverageEvidence | None,
    *,
    standing: Sequence[tuple[Observation, bool]],
    shared: bool,
) -> ReportDiagnostic:
    """Name a recorded gap this run derives no window for, and why it derives none.

    With evidence inside the window the gap is contradicted and the earliest is named.
    Without it the gap is unmatched: nothing disproves it, and the inputs of this run and
    of the one that recorded it may differ, which no disposition answers. A disposition
    answers the whole case, so a contradicted note advises a false positive only when no
    other recorded gap of its case stands. Each that does is named with why it stands:
    this run still derives it (True), or neither derives nor disproves it (False).
    """

    closed_at = gap.observed_at
    if closed_at is None:  # pragma: no cover - a gap is always observed at its window close
        raise ValueError(f"coverage gap {gap.observation_id} has no window close")
    described = f"{tracking_id} carries the recorded gap of {_gap_window(gap)}"
    others = ", and ".join(
        f"{_gap_window(other)}, which this run "
        + ("still derives" if still_derived else "neither derives nor disproves")
        for other, still_derived in standing
    )
    if evidence is None or evidence.at is None:
        tail = "the gap stays recorded"
        if others:
            tail = f"{tail}, and the case also carries {others}"
        return ReportDiagnostic(
            level=DiagnosticLevel.INFO,
            code="coverage_gap_unmatched",
            message=(
                f"{described}, and this run derives no such window and holds no verification "
                "inside it, so its inventory, as-of, class or calendar zone may differ from "
                f"the run that recorded the gap; {tail}"
            ),
            location=gap.source_record_id,
        )
    if others:
        advice = (
            f"but the case also carries {others}, so it stays open until every other gap it "
            "carries is contradicted or disposed on its own merits"
        )
    elif shared:
        advice = (
            "and every other recorded gap of the case is contradicted too, so an evaluation "
            "can dispose the case as a false positive"
        )
    else:
        advice = "and an evaluation can dispose it as a false positive"
    return ReportDiagnostic(
        level=DiagnosticLevel.INFO,
        code="coverage_gap_contradicted",
        message=(
            f"{described}, but {evidence.kind.value} {evidence.reference} on "
            f"{_coverage_label(evidence.resource)} verified it at {_iso(evidence.at)}, inside "
            f"that window, so this run derives no such window; the gap stays recorded, {advice}"
        ),
        location=gap.source_record_id,
    )


def _gap_window(gap: Observation) -> str:
    """Return a recorded gap as its window reads: rule, context subject and close."""

    closed = "" if gap.observed_at is None else _iso(gap.observed_at)
    rule = gap.context_key.split(":", 1)[0]
    return f"the {rule} window for {_coverage_label(gap.resource)} that closed {closed}"


def _gap_order(gap: Observation) -> tuple[str, str, str, str, str]:
    """Order gap records as their windows are ordered: by rule, subject and close."""

    closed = "" if gap.observed_at is None else _iso(gap.observed_at)
    rule = gap.context_key.split(":", 1)[0]
    subject = gap.resource
    return (rule, subject.resource_type, subject.resource_id, closed, gap.observation_id)


def coverage_diagnostics(coverage: CoverageResult) -> list[ReportDiagnostic]:
    """Return one note per warning an inventory entry raised, in entry order (type, then id).

    Each is located at the inventory's name and the entry's pair, so the same entry in the
    same inventory raises the same note whichever path or file name supplied it.
    """

    notes: list[ReportDiagnostic] = []
    for resource in coverage.resources:
        label = _coverage_label(resource.entry.ref)
        for code in resource.warnings:
            if code != DRIFT_LIKELIHOOD_UNKNOWN:
                raise ValueError(f"unhandled coverage warning {code!r}")
            notes.append(
                ReportDiagnostic(
                    level=DiagnosticLevel.WARNING,
                    code=code,
                    message=(
                        f'{label} declares driftLikely "unknown", so it carries {PDD_RULE}, '
                        "the shorter drift window, until the inventory says whether drift is "
                        "likely"
                    ),
                    location=f"{coverage.inventory.name} {label}",
                )
            )
    return notes


def _coverage_label(ref: ResourceRef) -> str:
    """Return a resource as `type:id`; a type never holds a colon, so it reads one way."""

    return f"{ref.resource_type}:{ref.resource_id}"


def _records_carry(count: int) -> str:
    return "1 compiled record carries" if count == 1 else f"{count} compiled records carry"


def _report_period(options: ReportOptions, report_name: str) -> tuple[datetime, datetime]:
    """Return the period a report selects by, or stop the run when there is none.

    A periodless `ReportOptions` is legitimate input for the historical activity
    report, so the options do not refuse it. A report that selects by period turns
    the absence into a compile diagnostic here, named after the report that needs
    it, rather than an attribute error deep inside selection.
    """

    if options.has_period:
        return options.period
    raise ReportCompileError(
        (
            ReportDiagnostic(
                level=DiagnosticLevel.ERROR,
                code="report_period_missing",
                message=(
                    f"{report_name} selects records by report period, so period_from "
                    "and period_to are required"
                ),
            ),
        )
    )


def _require_acceptance_rationales(records: Sequence[CompiledVulnerability]) -> None:
    """Stop the run when an accepted record carries no acceptance rationale.

    The official `acceptedVulnerabilityInfo` item requires `acceptanceRationale`, and
    an empty string would satisfy the schema while saying nothing. Only the reports
    that publish accepted records call this (ADR 0010 Decision 4); the Vulnerability
    Detail Report sets accepted records aside and does not need the rationale. Every
    offending record is named in one error, in record order, so an operator fixes
    the file once.
    """

    errors = [
        ReportDiagnostic(
            level=DiagnosticLevel.ERROR,
            code="acceptance_rationale_missing",
            message=(
                f"{record.tracking_id} is accepted but its evaluation records no "
                "acceptance rationale, which the accepted vulnerability report requires"
            ),
            location=record.source_record_id,
        )
        for record in records
        if record.status is CaseStatus.ACCEPTED and not _acceptance_rationale(record)
    ]
    if errors:
        raise ReportCompileError(errors)


def _acceptance_rationale(record: CompiledVulnerability) -> str | None:
    """Return the record's acceptance rationale, or None when missing or blank."""

    evaluation = record.evaluation
    rationale = evaluation.acceptance_rationale if evaluation is not None else None
    if rationale is None or not rationale.strip():
        return None
    return rationale


def _select_for_period(
    records: Sequence[CompiledVulnerability],
    period: tuple[datetime, datetime],
    diagnostics: list[ReportDiagnostic],
) -> tuple[list[CompiledVulnerability], list[AcceptedVulnerability], int]:
    """Split compiled records into reported, accepted, and excluded by period.

    `reportPeriod` is not a label. A vulnerability appears in the report for a period
    when it had activity in that period (VER-RPT-PER), with both bounds inclusive. Open
    KEV work stays in as well: under VDR-TFR-KEV a mitigated KEV is unresolved, so a
    record whose clock is open, detected and listed by the period end, is kept with no
    activity in the period (ADR 0012 Decision 7).

    An accepted record is set aside for the VER-RPT-AVI report of the same period only
    when that report would carry it, by the same activity rule (ADR 0010 Decision 2).
    One with no activity in the period is in neither report and is counted as excluded,
    so every record of the set lands in exactly one of the three Summary rows.
    """

    reported: list[CompiledVulnerability] = []
    accepted: list[AcceptedVulnerability] = []
    excluded = 0

    for record in records:
        if record.status is CaseStatus.ACCEPTED:
            reason = _period_exclusion_reason(record, period, state="is accepted")
            if reason is not None:
                excluded += 1
                diagnostics.append(
                    ReportDiagnostic(
                        level=DiagnosticLevel.INFO,
                        code="excluded_by_period",
                        message=f"{record.tracking_id} {reason}",
                        location=record.source_record_id,
                    )
                )
                continue
            evaluation = record.evaluation
            rationale = evaluation.acceptance_rationale if evaluation else None
            accepted.append(
                AcceptedVulnerability(
                    vulnerability=record,
                    acceptance_rationale=rationale or "",
                )
            )
            diagnostics.append(
                ReportDiagnostic(
                    level=DiagnosticLevel.INFO,
                    code="accepted_excluded",
                    message=(
                        f"{record.tracking_id} is an accepted vulnerability and belongs in "
                        "the VER-RPT-AVI report, not the Vulnerability Detail Report"
                    ),
                    location=record.source_record_id,
                )
            )
            continue
        if _keeps_open_kev_work(record, period):
            reported.append(record)
            continue
        reason = _period_exclusion_reason(record, period)
        if reason is not None:
            excluded += 1
            diagnostics.append(
                ReportDiagnostic(
                    level=DiagnosticLevel.INFO,
                    code="excluded_by_period",
                    message=f"{record.tracking_id} {reason}",
                    location=record.source_record_id,
                )
            )
            continue
        reported.append(record)
    return reported, accepted, excluded


def _keeps_open_kev_work(record: CompiledVulnerability, period: tuple[datetime, datetime]) -> bool:
    """Return whether an open KEV clock keeps a record in the Vulnerability Detail Report.

    The listing bound matters because nothing orders `as_of` against the period end: an
    August report compiled in September must not pull in a record that was quiet in
    August and became a KEV after it ended.
    """

    kev = record.kev
    if kev is None or kev.satisfied:
        return False
    period_to = period[1]
    if record.detected_at > period_to:
        return False
    return min(entry.date_added for entry in kev.entries) <= period_to.astimezone(UTC).date()


def _accepted(record: CompiledVulnerability) -> AcceptedVulnerability:
    """Pair an accepted record with the rationale its evaluation recorded.

    Only the reports that publish accepted vulnerabilities call this, and only after
    they have checked that every accepted record carries a rationale, so a missing one
    here is a programming error rather than an input error.
    """

    rationale = _acceptance_rationale(record)
    if rationale is None:  # pragma: no cover - callers guard before reaching here
        raise AssertionError(f"{record.tracking_id} is accepted with no acceptance rationale")
    return AcceptedVulnerability(vulnerability=record, acceptance_rationale=rationale)


def _period_exclusion_reason(
    record: CompiledVulnerability,
    period: tuple[datetime, datetime],
    *,
    state: str | None = None,
) -> str | None:
    """Return why a record falls outside the report period, or None if it belongs.

    `state` is how the message names the record's standing when it had no activity in
    the period. The Vulnerability Detail Report leaves it unset and the message reads
    the record's disposition; a report that only selects accepted records passes the
    standing that applies to all of them.
    """

    period_from, period_to = period
    if record.detected_at > period_to:
        return f"was detected {_iso(record.detected_at)}, after the period ended {_iso(period_to)}"
    if not record.has_disposition:
        return None
    if any(period_from <= instant <= period_to for instant in record.activity_instants):
        return None
    if state is None:
        state = f"has disposition {record.final_disposition!r}"
    return f"{state} and no recorded activity between {_iso(period_from)} and {_iso(period_to)}"


def _build_record(
    *,
    group: VulnerabilityGroup,
    detected_at: datetime,
    detected_at_source: str,
    evaluation: EvaluationInput | None,
    policy: SelectedPolicy,
    snapshot: RuleSourceSnapshot,
    options: ReportOptions,
    kev_rule: SelectedRule | None = None,
) -> CompiledVulnerability:
    if evaluation is not None:
        evaluation = _canonical_reductions(evaluation)
    status = evaluation.resolved_status if evaluation is not None else None
    if evaluation is not None and evaluation.case_status is CaseStatus.CLOSED and status is None:
        raise ReportCompileError(
            (
                ReportDiagnostic(
                    level=DiagnosticLevel.ERROR,
                    code="closed_without_disposition",
                    message=(
                        f"{group.tracking_id} is closed with no recorded disposition; "
                        "supply closedDisposition"
                    ),
                    location=evaluation.location,
                ),
            )
        )

    is_accepted = status is CaseStatus.ACCEPTED
    final_disposition = None if status is None else FINAL_DISPOSITIONS.get(status)
    if status is not None and status not in ACTIVE_STATUSES and not is_accepted:
        if final_disposition is None:  # pragma: no cover - table above is exhaustive
            raise AssertionError(f"unmapped case status: {status}")
    disposition_recorded = final_disposition is not None

    deadlines, overdue_clauses = _compute_deadlines(
        detected_at=detected_at,
        evaluation=evaluation,
        policy=policy,
        options=options,
        disposition_recorded=disposition_recorded,
        acceptance_recorded=is_accepted,
    )
    # The KEV clock runs after the other three, so deadlines and clauses read EVU, PVR,
    # MAV, KEV. An accepted record keeps its clock but is never officially overdue on it.
    kev: KevClock | None = None
    catalog = options.kev_catalog
    if kev_rule is not None and catalog is not None:
        entries = catalog.matches(
            group.source_identifiers, on_or_before=options.as_of.astimezone(UTC).date()
        )
        if entries:
            kev = kev_clock(entries, status=status, as_of=options.as_of)
            deadlines += (_kev_deadline(kev, kev_rule),)
            if kev.past_due and not is_accepted:
                overdue_clauses += (
                    _kev_clause(kev, kev_rule, catalog, options, detected_at, status),
                )
    explanation = ""
    if overdue_clauses:
        explanation = _explanation(overdue_clauses, policy, snapshot, options)

    tracking_id = group.tracking_id
    if evaluation is not None and evaluation.tracking_id is not None:
        tracking_id = evaluation.tracking_id

    return CompiledVulnerability(
        tracking_id=tracking_id,
        source_type=group.source_type,
        source_record_id=group.source_record_id,
        context_key=group.context_key,
        description=_describe(group),
        detected_at=detected_at,
        detected_at_source=detected_at_source,
        detection_source=group.detection_source,
        observation_ids=group.observation_ids,
        resources=group.resources,
        source_identifiers=group.source_identifiers,
        deadlines=deadlines,
        is_overdue=bool(overdue_clauses),
        overdue_explanation=explanation,
        evaluation=evaluation,
        final_disposition=final_disposition,
        remediated=status is CaseStatus.REMEDIATED,
        status=status,
        untimestamped_observation_ids=group.untimestamped_observation_ids,
        original_tracking_id=group.tracking_id,
        kev_checked=kev_rule is not None,
        kev=kev,
    )


def _canonical_reductions(evaluation: EvaluationInput) -> EvaluationInput:
    """Return the evaluation with its completed PAIN reductions in canonical order.

    Order is by instant, then by rating. The stateless path reads reductions in the
    order an evaluations file states them and the persisted path in the order they were
    appended, and neither order is a fact about the vulnerability, so ordering them
    here is what lets the two paths render the same history the same way (ADR 0008
    Decision 5). Both renderings read the record this returns, so the JSON array and
    the Markdown line can never disagree.
    """

    events = evaluation.pain_reduction_events
    ordered = tuple(sorted(events, key=lambda item: (item.reduced_at, int(item.rating))))
    if ordered == events:
        return evaluation
    return replace(evaluation, pain_reduction_events=ordered)


def _describe(group: VulnerabilityGroup) -> str:
    title = group.title.strip()
    if not title:
        return group.source_record_id
    # A title that already leads with the record id, as an HDF CVE control's does, is kept
    # as written rather than prefixed twice; the match is exact and case-sensitive.
    record_id = group.source_record_id
    if title == record_id or title.startswith(f"{record_id}: "):
        return title
    return f"{record_id}: {title}"


def _compute_deadlines(
    *,
    detected_at: datetime,
    evaluation: EvaluationInput | None,
    policy: SelectedPolicy,
    options: ReportOptions,
    disposition_recorded: bool,
    acceptance_recorded: bool,
) -> tuple[tuple[CompiledDeadline, ...], tuple[str, ...]]:
    as_of = options.as_of
    class_name = options.certification_class.value
    deadlines: list[CompiledDeadline] = []
    clauses: list[str] = []

    evaluation_deadline = policy.evaluation_deadline(detected_at)
    evaluated = evaluation is not None
    deadlines.append(_compiled(evaluation_deadline, anchor="detection", satisfied=evaluated))
    if not evaluated and as_of > evaluation_deadline.due_at:
        clauses.append(
            f"{evaluation_deadline.rule_id} ({evaluation_deadline.force.value}, "
            f"Class {class_name}): the evaluation window opened at detection "
            f"{_iso(detected_at)} and closed {_iso(evaluation_deadline.due_at)} "
            "with no evaluation recorded."
        )

    if evaluation is None:
        return tuple(deadlines), tuple(clauses)

    resolved = disposition_recorded or acceptance_recorded
    response = policy.response_deadline(
        evaluation.completed_at,
        pain=evaluation.pain,
        is_internet_reachable=evaluation.is_internet_reachable,
        is_likely_exploitable=evaluation.is_likely_exploitable,
    )
    if response is not None:
        deadlines.append(_compiled(response, anchor="evaluation", satisfied=resolved))
        if not resolved and as_of > response.due_at:
            clauses.append(
                f"{response.rule_id} ({response.force.value}, Class {class_name}): the "
                f"response target for PAIN {evaluation.pain.name}, "
                f"{_reachability(evaluation.is_internet_reachable)}, "
                f"{_exploitability(evaluation.is_likely_exploitable)} ran from the "
                f"completed evaluation {_iso(evaluation.completed_at)} and passed "
                f"{_iso(response.due_at)} with no disposition recorded."
            )

    acceptance = policy.acceptance_deadline(evaluation.completed_at)
    deadlines.append(_compiled(acceptance, anchor="evaluation", satisfied=resolved))
    if not resolved and as_of > acceptance.due_at:
        clauses.append(
            f"{acceptance.rule_id} ({acceptance.force.value}, Class {class_name}): the "
            f"{acceptance.timeframe.display_amount}-{acceptance.timeframe.unit.value} "
            f"categorization threshold ran from the completed evaluation "
            f"{_iso(evaluation.completed_at)} and passed {_iso(acceptance.due_at)} with "
            "no disposition and no acceptance recorded."
        )
    return tuple(deadlines), tuple(clauses)


def _compiled(deadline: PolicyDeadline, *, anchor: str, satisfied: bool) -> CompiledDeadline:
    return CompiledDeadline(
        rule_id=deadline.rule_id,
        rule_name=deadline.rule_name,
        force=deadline.force.value,
        anchor=anchor,
        start_at=deadline.start_at,
        due_at=deadline.due_at,
        timeframe_amount=deadline.timeframe.display_amount,
        timeframe_unit=deadline.timeframe.unit.value,
        satisfied=satisfied,
    )


def _kev_deadline(kev: KevClock, rule: SelectedRule) -> CompiledDeadline:
    """Return the VDR-TFR-KEV deadline, whose due date is the catalog's, not a timeframe."""

    return CompiledDeadline(
        rule_id=rule.rule_id,
        rule_name=rule.name,
        force=rule.force.value,
        anchor="catalog",
        start_at=kev.start_at,
        due_at=kev.due_at,
        timeframe_amount=None,
        timeframe_unit=None,
        satisfied=kev.satisfied,
    )


def _kev_clause(
    kev: KevClock,
    rule: SelectedRule,
    catalog: KevCatalog,
    options: ReportOptions,
    detected_at: datetime,
    status: CaseStatus | None,
) -> str:
    """Explain a past-due KEV clock; only a past-due clock is written, so "ended" is past."""

    bound = kev.bound
    clause = (
        f"{rule.rule_id} ({rule.force.value}, Class {options.certification_class.value}): "
        f"the CISA KEV catalog (version {catalog.catalog_version}, released "
        f"{_iso(catalog.date_released)}) lists {bound.cve_id} with due date "
        f"{bound.due_date.isoformat()}, which ended {_iso(kev.due_at)} with no "
        "remediation recorded."
    )
    if detected_at > kev.due_at:
        clause += f" The due date had passed before detection at {_iso(detected_at)}."
    if status in (CaseStatus.PARTIALLY_MITIGATED, CaseStatus.FULLY_MITIGATED):
        clause += " A recorded mitigation does not stop this clock."
    return clause


def _explanation(
    clauses: Sequence[str],
    policy: SelectedPolicy,
    snapshot: RuleSourceSnapshot,
    options: ReportOptions,
) -> str:
    parts = list(clauses)
    parts.append(f"Rules dataset commit {policy.provenance.commit}.")
    obtain = _optional_adoption_notice(snapshot, options.as_of)
    if obtain:
        parts.append(obtain)
    return " ".join(parts)


def _optional_adoption_notice(snapshot: RuleSourceSnapshot, as_of: datetime) -> str:
    dates = _obtain_dates(snapshot)
    if not dates:
        return ""
    earliest = min(dates.values())
    if as_of.astimezone(UTC).date().isoformat() >= earliest:
        return ""
    if len(set(dates.values())) == 1:
        rendered = earliest
    else:
        rendered = " and ".join(
            f"{value} ({document})" for document, value in sorted(dates.items())
        )
    return f"The VDR and VER rulesets are in their optional-adoption period until {rendered}."


def _obtain_dates(snapshot: RuleSourceSnapshot) -> dict[str, str]:
    data = snapshot.data
    dates: dict[str, str] = {}
    for document_id in ("VDR", "VER"):
        node: Any = data.get("FRR", {}).get(document_id, {})
        for key in ("info", "effective", "date", "obtain"):
            if not isinstance(node, dict):
                node = None
                break
            node = node.get(key)
        if isinstance(node, str) and node:
            dates[document_id] = node
    return dates


def _reachability(value: bool) -> str:
    return "internet reachable" if value else "not internet reachable"


def _exploitability(value: bool) -> str:
    return "likely exploitable" if value else "not likely exploitable"


def _parser_versions(observations: Sequence[Observation]) -> tuple[tuple[str, str], ...]:
    pairs = {(item.parser_name, item.parser_version) for item in observations}
    return tuple(sorted(pairs))


def _schema_provenance(report_schema: ReportSchema) -> SchemaProvenance:
    """Describe the bundled schema one report is validated against and published with."""

    bundle = load_bundled_schema_bundle()
    document = bundle.document(report_schema.value)
    return SchemaProvenance(
        repository=bundle.manifest.repository,
        commit=bundle.manifest.commit,
        schema_id=document.entry.schema_id,
        schema_version=document.entry.version,
        schema_sha256=document.content_sha256,
    )


def _validate_document(
    report_schema: ReportSchema,
    document: dict[str, Any],
) -> SchemaValidationResult:
    """Validate one compiled document against its bundled schema, or stop the run.

    A document that fails here was built by ComplyRoll from inputs that already
    passed their own checks, so the failure is a defect in the compiler and the run
    ends with the validator's own findings rather than an invalid report on disk.
    """

    validation = validate_bundled_report(report_schema, document)
    if not validation.is_valid:
        raise ReportCompileError(
            tuple(
                ReportDiagnostic(
                    level=DiagnosticLevel.ERROR,
                    code="schema_invalid",
                    message=(
                        "the compiled report failed official schema validation, which is a "
                        f"ComplyRoll defect: {issue.validator}: {issue.message}"
                    ),
                    location=issue.instance_pointer or "<root>",
                )
                for issue in validation.issues
            )
        )
    return validation


def _common_extension(
    records: Sequence[CompiledVulnerability],
    metadata: ReportMetadata,
    diagnostics: Sequence[ReportDiagnostic],
) -> dict[str, Any]:
    """Build the `x-complyroll` block every report shares.

    Each projection adds its own counters on top. The keys are sorted when the JSON is
    written, so where a projection inserts them does not reach the bytes.
    """

    options = metadata.options
    extension: dict[str, Any] = {
        "generator": {"name": GENERATOR_NAME, "version": metadata.generator_version},
        "generatedAt": _iso(options.as_of),
        "calendarTimezone": options.calendar_timezone,
        "certificationClass": options.certification_class.value,
        "rulesSource": {
            "repository": metadata.rules_provenance.repository,
            "commit": metadata.rules_provenance.commit,
            "datasetVersion": metadata.rules_provenance.dataset_version,
            "datasetLastUpdated": metadata.rules_provenance.dataset_last_updated,
            "sha256": metadata.rules_provenance.dataset_sha256,
        },
        "schemaSource": {
            "repository": metadata.schema_provenance.repository,
            "commit": metadata.schema_provenance.commit,
            "schemaId": metadata.schema_provenance.schema_id,
            "schemaVersion": metadata.schema_provenance.schema_version,
            "sha256": metadata.schema_provenance.schema_sha256,
        },
        "parserVersions": dict(metadata.parser_versions),
        "artifacts": [artifact.to_dict() for artifact in metadata.artifacts],
        "detectionTimeAttestation": _attestation_block(records, metadata),
        "diagnostics": [diagnostic.to_dict() for diagnostic in diagnostics],
        "disclaimer": DISCLAIMER,
    }
    # Only a run that recorded a detection process failure carries the key, so a report
    # compiled without one is byte-identical to one compiled before it existed.
    if metadata.detection_failures:
        extension["detectionFailures"] = [item.to_dict() for item in metadata.detection_failures]
    catalog = options.kev_catalog
    if catalog is not None:
        extension["kevSource"] = {
            "name": catalog.name,
            "sha256": catalog.sha256,
            "sizeBytes": catalog.size_bytes,
            "catalogVersion": catalog.catalog_version,
            "dateReleased": _iso(catalog.date_released),
            "count": catalog.declared_count,
            "entriesConsidered": catalog.considered(options.as_of.astimezone(UTC).date()),
        }
    # Only a run given an inventory carries the key, so every report compiled without one
    # is byte-identical to one compiled before coverage existed (ADR 0015).
    if metadata.coverage is not None:
        extension["coverage"] = metadata.coverage.to_dict(gap_records=metadata.coverage_gap_records)
    return extension


def _build_document(
    records: Sequence[CompiledVulnerability],
    metadata: ReportMetadata,
    diagnostics: Sequence[ReportDiagnostic],
) -> dict[str, Any]:
    options = metadata.options
    extension = _common_extension(records, metadata, diagnostics)
    extension["excludedByPeriod"] = metadata.excluded_by_period
    return {
        "certificationPackageOverviewUri": options.package_uri,
        "reportPeriod": _report_period_block(options),
        "vulnerabilities": [record.to_official_dict() for record in records],
        EXTENSION_KEY: extension,
    }


def _report_period_block(options: ReportOptions) -> dict[str, str]:
    """Build the official `reportPeriod` object from options that carry a period."""

    period_from, period_to = options.period
    return {"from": _iso(period_from), "to": _iso(period_to)}


def _attestation_block(
    records: Sequence[CompiledVulnerability],
    metadata: ReportMetadata,
) -> dict[str, Any] | None:
    """Return the `detectionTimeAttestation` object, or None when none was needed.

    One shared instant publishes the scalar form the stateless path has always
    emitted. Differing instants, reachable only when history attested cases
    separately, publish one entry per instant instead: a single report-level
    `detectedAt` would be a false statement about the records it does not cover, so
    there is no scalar key at all (ADR 0008 amendment).
    """

    applied_to = metadata.attestation_applied_to
    if not applied_to:
        return None
    shared = metadata.attestation
    if shared is not None:
        return {
            "detectedAt": _iso(shared),
            "appliedTo": list(applied_to),
            "count": len(applied_to),
        }
    return {
        "appliedTo": list(applied_to),
        "count": len(applied_to),
        "attestations": [
            {"detectedAt": _iso(instant), "appliedTo": list(tracking_ids)}
            for instant, tracking_ids in _attestation_groups(records)
        ],
    }


# --------------------------------------------------------------------------------------
# Markdown twin. Every number below comes from the compiled records, never from the JSON.
# --------------------------------------------------------------------------------------


def _render_markdown(report: CompiledVdtReport) -> str:
    metadata = report.metadata
    records = report.vulnerabilities
    lines: list[str] = []
    write = lines.append

    _write_header(write, metadata.options, title="Vulnerability Detail Report", period=True)
    _write_provenance(write, metadata)

    write("## Summary")
    write("")
    write("| Measure | Count |")
    write("|---|---:|")
    write(f"| Vulnerabilities reported | {len(records)} |")
    write(f"| Evaluated | {sum(1 for item in records if item.is_evaluated)} |")
    write(f"| Not yet evaluated | {sum(1 for item in records if not item.is_evaluated)} |")
    write(f"| Overdue | {sum(1 for item in records if item.is_overdue)} |")
    _write_kev_summary(write, records, metadata.options)
    write(f"| Accepted, reported under VER-RPT-AVI | {len(report.accepted)} |")
    write(f"| Excluded by report period | {metadata.excluded_by_period} |")
    for rating in PainRating:
        count = sum(1 for item in records if item.current_rating is rating)
        write(f"| Current PAIN {rating.name} | {count} |")
    write("")

    _write_vulnerability_table(
        write,
        records,
        heading="Vulnerabilities",
        empty_message="No open vulnerabilities were reported for this period.",
        details_heading="Vulnerability details",
        as_of=metadata.options.as_of,
    )
    _write_attestation_section(write, records, metadata)
    _write_inputs(write, metadata)
    _write_coverage(write, metadata)
    _write_diagnostics_section(write, report.diagnostics)
    _write_footer(write)
    return "\n".join(lines) + "\n"


def _write_kev_summary(
    write: Callable[[str], None],
    records: Sequence[CompiledVulnerability],
    options: ReportOptions,
) -> None:
    """Write the two KEV Summary rows, which a report carries only with a catalog.

    `records` is the population the report's Overdue row counts, so the two rows sit
    beside it: an accepted record past its KEV due date is counted here and never there.
    """

    if options.kev_catalog is None:
        return
    known = sum(1 for item in records if item.kev is not None)
    past_due = sum(1 for item in records if item.kev is not None and item.kev.past_due)
    write(f"| Known exploited, CISA KEV | {known} |")
    write(f"| Past a CISA KEV due date | {past_due} |")


def _write_header(
    write: Callable[[str], None],
    options: ReportOptions,
    *,
    title: str,
    period: bool,
) -> None:
    """Open a Markdown twin with its title and the run's identifying inputs.

    `period` is False for the report that has no period, so the line is left out
    rather than printed empty.
    """

    write(f"# {title}")
    write("")
    write(f"- **Certification package:** {_cell(options.package_uri)}")
    if period:
        period_from, period_to = options.period
        write(f"- **Report period:** {_iso(period_from)} to {_iso(period_to)}")
    write(f"- **Certification class:** {options.certification_class.value}")
    write(f"- **Generated at:** {_iso(options.as_of)}")
    write(f"- **Calendar timezone:** {_cell(options.calendar_timezone)}")
    write("")


def _write_provenance(write: Callable[[str], None], metadata: ReportMetadata) -> None:
    write("## Provenance")
    write("")
    write("| Source | Reference | Digest |")
    write("|---|---|---|")
    rules = metadata.rules_provenance
    schema = metadata.schema_provenance
    write(
        f"| Rules dataset | {_cell(rules.repository)} at {rules.commit} "
        f"(version {_cell(rules.dataset_version)}, updated {_cell(rules.dataset_last_updated)}) "
        f"| {rules.dataset_sha256} |"
    )
    write(
        f"| Report schema | {_cell(schema.repository)} at {schema.commit} "
        f"({_cell(schema.schema_id)} version {_cell(schema.schema_version)}) "
        f"| {schema.schema_sha256} |"
    )
    catalog = metadata.options.kev_catalog
    if catalog is not None:
        considered = catalog.considered(metadata.options.as_of.astimezone(UTC).date())
        write(
            f"| KEV catalog | {_cell(catalog.name)}, CISA KEV catalog version "
            f"{_cell(catalog.catalog_version)}, released {_iso(catalog.date_released)}, "
            f"{considered} entries | {catalog.sha256} |"
        )
    write(f"| Generator | {GENERATOR_NAME} {_cell(metadata.generator_version)} | n/a |")
    write("")


def _vulnerability_row(item: CompiledVulnerability) -> str:
    """Render one record as a row of the shared vulnerability table."""

    evaluation = item.evaluation
    next_due = item.next_due
    return (
        "| "
        + " | ".join(
            (
                _cell(item.tracking_id),
                _cell(item.source_record_id),
                str(len(item.resources)),
                _iso(item.detected_at),
                _iso(evaluation.completed_at) if evaluation else "n/a",
                _flag(evaluation.is_internet_reachable) if evaluation else "n/a",
                _flag(evaluation.is_likely_exploitable) if evaluation else "n/a",
                item.current_rating.name if item.current_rating else "n/a",
                (f"{_iso(next_due.due_at)} ({_cell(next_due.rule_id)})" if next_due else "n/a"),
                _flag(item.is_overdue),
                _cell(_disposition_label(item)),
            )
        )
        + " |"
    )


def _write_vulnerability_table(
    write: Callable[[str], None],
    records: Sequence[CompiledVulnerability],
    *,
    heading: str,
    empty_message: str,
    details_heading: str,
    as_of: datetime,
    rationales: Mapping[str, str] | None = None,
) -> None:
    """Write one table of records followed by their detail sections.

    An empty table is one sentence under the heading and no details heading at all.
    `rationales` maps tracking identifiers to acceptance rationales for the tables
    that publish accepted records; the detail section prints the rationale when the
    record has one. `as_of` is the run's instant, which the KEV line reads (ADR 0012).
    """

    write(f"## {heading}")
    write("")
    if not records:
        write(empty_message)
        write("")
        return
    write(
        "| Tracking ID | Source record | Resources | Detected | Evaluation completed "
        "| IRV | LEV | PAIN | Next due | Overdue | Disposition |"
    )
    write("|---|---|---:|---|---|---|---|---|---|---|---|")
    for item in records:
        write(_vulnerability_row(item))
    write("")

    write(f"## {details_heading}")
    write("")
    for item in records:
        rationale = None if rationales is None else rationales.get(item.tracking_id)
        _write_detail(write, item, as_of=as_of, acceptance_rationale=rationale)


def _write_attestation_section(
    write: Callable[[str], None],
    records: Sequence[CompiledVulnerability],
    metadata: ReportMetadata,
) -> None:
    write("## Detection time attestation")
    write("")
    attested = metadata.attestation_applied_to
    attestation = metadata.attestation
    system_types = {item.source_type for item in records if item.detected_at_source == "system"}
    if not attested and system_types:
        write(_system_detection_sentence(system_types))
    elif not attested:
        write(
            "Every reported vulnerability carried a detection time from its source artifact. "
            "No attestation was needed."
        )
    elif attestation is None:
        write(
            "The operator attested per-case detection times for "
            f"{len(attested)} vulnerability record(s) whose source artifacts declare no "
            "assessment timestamp. ComplyRoll never substitutes file modification or "
            "ingestion time for a detection time."
        )
        write("")
        for instant, tracking_ids in _attestation_groups(records):
            write(f"- **{_iso(instant)}:** {', '.join(_cell(value) for value in tracking_ids)}")
    else:
        write(
            f"The operator attested a detection time of {_iso(attestation)} for "
            f"{len(attested)} vulnerability record(s) whose source artifacts declare no "
            "assessment timestamp. ComplyRoll never substitutes file modification or "
            "ingestion time for a detection time."
        )
    write("")


def _system_detection_sentence(source_types: set[str]) -> str:
    """Say what timed each kind of system record; a failure-only run reads as it always has."""

    clauses = []
    if source_types - {COVERAGE_GAP_SOURCE_TYPE}:
        clauses.append(
            "for a detection process failure, from the instant ComplyRoll or the scanner "
            "recorded it"
        )
    if COVERAGE_GAP_SOURCE_TYPE in source_types:
        clauses.append("for a coverage gap, from the instant its coverage window closed")
    return (
        "Every reported vulnerability carried a detection time from its source artifact or, "
        + " and, ".join(clauses)
        + ". No attestation was needed."
    )


def _write_inputs(write: Callable[[str], None], metadata: ReportMetadata) -> None:
    write("## Inputs")
    write("")
    write("| Artifact | SHA-256 | Parser | Observations |")
    write("|---|---|---|---:|")
    for artifact in metadata.artifacts:
        write(
            f"| {_cell(artifact.name)} | {artifact.sha256[:12]} | "
            f"{_cell(artifact.parser)} {_cell(artifact.parser_version)} "
            f"| {artifact.observation_count} |"
        )
    write("")
    _write_detection_failures(write, metadata.detection_failures)


def _write_detection_failures(
    write: Callable[[str], None],
    failures: Sequence[CompiledDetectionFailure],
) -> None:
    """Write the Inputs subsection listing each detection process failure, if any.

    A failed artifact is not in the Inputs table, which lists what was read, so this is
    where a reader finds it. Nothing is written when the run recorded no failure.
    """

    if not failures:
        return
    write("### Detection process failures")
    write("")
    write("| Artifact | SHA-256 | Parser | Class | Observed at | Clock | Tracking ID |")
    write("|---|---|---|---|---|---|---|")
    for item in failures:
        write(
            f"| {_cell(item.name)} | {_cell(item.sha256[:12])} "
            f"| {_cell(item.parser)} {_cell(item.parser_version)} "
            f"| {_cell(item.failure_class)} | {_cell(_iso(item.observed_at))} "
            f"| {_cell(item.clock)} | {_cell(item.tracking_id)} |"
        )
    write("")


def _write_coverage(write: Callable[[str], None], metadata: ReportMetadata) -> None:
    """Write the Coverage section, the twin of `x-complyroll.coverage` (ADR 0015).

    Every summary row, resource, clock, window, unregistered resource and piece of listed
    evidence the block carries is written here, from the same coverage result. Nothing is
    written when the run was given no inventory.
    """

    coverage = metadata.coverage
    if coverage is None:
        return
    inventory = coverage.inventory
    write("## Coverage")
    write("")
    write(
        f"Coverage of the inventory {_cell(inventory.name)} ({inventory.entry_count} entries, "
        f"{inventory.size_bytes} bytes, SHA-256 {inventory.sha256}) as of "
        f"{_iso(coverage.as_of)}, with clocks from rules dataset commit "
        f"{metadata.rules_provenance.commit}."
    )
    write("")
    write(COVERAGE_BASIS)
    write("")

    write("### Coverage by rule")
    write("")
    write("| Rule | Force | Expected | Current | Stale | Missing | Unanchored | Undetermined |")
    write("|---|---|---:|---:|---:|---:|---:|---:|")
    for row in coverage.summary:
        write(
            f"| {row.rule_id} | {row.force.value} | {row.expected} | {row.current} "
            f"| {row.stale} | {row.missing} | {row.unanchored} | {row.undetermined} |"
        )
    write("")

    write("### Resources")
    write("")
    write(
        "| Resource | Kind | Aliases | Drift likely | Sample group | Job | Expected since "
        "| Decommissioned | Last examined | Last verified | Examined | Untimed | Clocks |"
    )
    write("|---|---|---|---|---|---|---|---|---|---|---:|---:|---|")
    for resource in coverage.resources:
        write(_coverage_resource_row(resource))
    write("")

    write("### Clocks")
    write("")
    write(
        "| Resource | Rule | Force | Status | Anchor | Anchored at | Due at | Evidence | Stand-in |"
    )
    write("|---|---|---|---|---|---|---|---|---|")
    for resource in coverage.resources:
        label = _cell(_coverage_label(resource.entry.ref))
        for clock in resource.clocks:
            write(
                f"| {label} | {clock.rule_id} | {clock.force.value} | {clock.status.value} "
                f"| {'n/a' if clock.anchor is None else clock.anchor.value} "
                f"| {_optional_iso(clock.anchor_at)} | {_optional_iso(clock.due_at)} "
                f"| {_coverage_evidence(clock.evidence)} | {_coverage_ref(clock.stand_in)} |"
            )
    write("")

    write("### Windows")
    write("")
    # Only a gap-aware run grows the table, so every earlier twin keeps its bytes.
    gap_records = metadata.coverage_gap_records
    if not coverage.windows:
        write("No window closed without a verification.")
    else:
        header = (
            "| Rule | Context | Force | Anchor | Anchored at | Closed at | Resumed at "
            "| Evidence | Stand-in |"
        )
        rule = "|---|---|---|---|---|---|---|---|---|"
        if gap_records is not None:
            write(_RECORDED_WINDOW_NOTE)
            write("")
            header += " Recorded | Tracking ID |"
            rule += "---|---|"
        write(header)
        write(rule)
        for window in coverage.windows:
            line = (
                f"| {window.rule_id} | {_cell(window.context_key)} | {window.force.value} "
                f"| {window.anchor.value} | {_iso(window.anchor_at)} | {_iso(window.closed_at)} "
                f"| {_optional_iso(window.resumed_at)} | {_coverage_evidence(window.evidence)} "
                f"| {_coverage_ref(window.stand_in)} |"
            )
            if gap_records is not None:
                tracking_id = gap_records[window]
                recorded = "no" if tracking_id is None else "yes"
                line += f" {recorded} | {_cell(tracking_id or 'n/a')} |"
            write(line)
    write("")

    write("### Unregistered resources")
    write("")
    if not coverage.unregistered:
        write("Every observed resource is in the inventory.")
    else:
        write("| Resource | Observations |")
        write("|---|---:|")
        for item in coverage.unregistered:
            write(f"| {_coverage_ref(item.resource)} | {item.observations} |")
    write("")

    _write_coverage_evidence(
        write,
        "Untimed evidence",
        "No inventory resource has untimed evidence.",
        [(resource, resource.untimed) for resource in coverage.resources],
    )
    _write_coverage_evidence(
        write,
        "Evidence after decommissioning",
        "No evidence was observed after a resource was decommissioned.",
        [(resource, resource.after_decommission) for resource in coverage.resources],
    )
    write("### Evidence after as-of")
    write("")
    if not coverage.later:
        write("No evidence was observed after as-of.")
    for evidence in coverage.later:
        write(f"- {_coverage_evidence(evidence)}")
    write("")


def _coverage_resource_row(resource: ResourceCoverage) -> str:
    """Render one resource row; a missing clock names the untimed evidence beside it."""

    entry = resource.entry
    untimed = len(resource.untimed)
    statuses = []
    for clock in resource.clocks:
        status = f"{clock.rule_id} {clock.force.value} {clock.status.value}"
        if clock.status is CoverageStatus.MISSING and untimed:
            status += f" ({untimed} untimed)"
        statuses.append(status)
    aliases = ", ".join(_coverage_ref(alias) for alias in entry.aliases) or "n/a"
    return (
        "| "
        + " | ".join(
            (
                _cell(_coverage_label(entry.ref)),
                "attested" if resource.attested else "machine",
                aliases,
                _drift_label(entry.drift_likely),
                _cell(entry.sample_group or "n/a"),
                _cell(entry.job or "n/a"),
                _iso(entry.expected_since),
                _optional_iso(entry.decommissioned_at),
                _optional_iso(resource.last_examined),
                _optional_iso(resource.last_verified),
                str(resource.examined_observations),
                str(untimed),
                "; ".join(statuses),
            )
        )
        + " |"
    )


def _write_coverage_evidence(
    write: Callable[[str], None],
    heading: str,
    empty_message: str,
    listed: Sequence[tuple[ResourceCoverage, Sequence[CoverageEvidence]]],
) -> None:
    """Write one evidence list, one line per resource that has any."""

    write(f"### {heading}")
    write("")
    lines = [
        f"- **{_cell(_coverage_label(resource.entry.ref))}:** "
        + "; ".join(_coverage_evidence(item) for item in evidence)
        for resource, evidence in listed
        if evidence
    ]
    for line in lines or [empty_message]:
        write(line)
    write("")


def _coverage_evidence(evidence: CoverageEvidence | None) -> str:
    """Name one piece of evidence: the observation fingerprint, or the attested reference."""

    if evidence is None:
        return "n/a"
    if evidence.disposition is None:
        text = f"attested: {_cell(evidence.reference)}"
    else:
        text = f"observation {evidence.reference} ({evidence.disposition.value})"
    text += f" on {_coverage_ref(evidence.resource)}"
    return text + (", untimed" if evidence.at is None else f" at {_iso(evidence.at)}")


def _coverage_ref(ref: ResourceRef | None) -> str:
    return "n/a" if ref is None else _cell(_coverage_label(ref))


def _drift_label(value: bool | str | None) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, bool):
        return _flag(value)
    return _cell(value)


def _optional_iso(value: datetime | None) -> str:
    return "n/a" if value is None else _iso(value)


def _write_diagnostics_section(
    write: Callable[[str], None],
    diagnostics: Sequence[ReportDiagnostic],
) -> None:
    write("## Diagnostics")
    write("")
    if not diagnostics:
        write("No diagnostics were raised.")
    else:
        for diagnostic in diagnostics:
            location = f" [{_cell(diagnostic.location)}]" if diagnostic.location else ""
            write(
                f"- **{diagnostic.level.value}** {_cell(diagnostic.code)}: "
                f"{_cell(diagnostic.message)}{location}"
            )
    write("")


def _write_footer(write: Callable[[str], None]) -> None:
    write("---")
    write("")
    write(DISCLAIMER)


def _disposition_label(item: CompiledVulnerability) -> str:
    """Name the record's standing the way the Markdown twins print it.

    A record with a final disposition prints that disposition. An accepted record has
    none, since acceptance is not a final disposition in the official enumeration, so
    it prints as accepted; everything else is active.
    """

    if item.final_disposition:
        return item.final_disposition
    if item.status is CaseStatus.ACCEPTED:
        return "accepted"
    return "active"


def _write_detail(
    write: Callable[[str], None],
    item: CompiledVulnerability,
    *,
    as_of: datetime,
    acceptance_rationale: str | None = None,
) -> None:
    """Render one vulnerability's full audit detail into the Markdown twin.

    The JSON extension and this section carry the same material, so neither
    rendering omits what the other holds (ADR 0007 amendment). The acceptance
    rationale is printed only when the caller passes one, since only the reports
    that publish accepted records carry it.
    """

    evaluation = item.evaluation
    write(f"### {_cell(item.tracking_id)}: {_cell(item.source_record_id)}")
    write("")
    write(f"- **Description:** {_cell(item.description)}")
    write(f"- **Detection source:** {_cell(item.detection_source)}")
    write(f"- **Detected at:** {_iso(item.detected_at)} (source: {_cell(item.detected_at_source)})")
    _write_observation_ids(write, item)
    resources = ", ".join(
        f"{_cell(resource.resource_type)} {_cell(resource.resource_id)}"
        for resource in item.resources
    )
    write(f"- **Affected resources:** {resources or 'n/a'}")
    identifiers = ", ".join(_cell(value) for value in item.source_identifiers)
    write(f"- **Source identifiers:** {identifiers or 'n/a'}")
    if item.kev_checked:
        write(f"- **Known exploited:** {_kev_line(item.kev, as_of)}")

    if evaluation is None:
        write("- **Evaluation:** not yet completed")
    else:
        write(
            f"- **Evaluation completed:** {_iso(evaluation.completed_at)} by "
            f"{_cell(evaluation.evaluator)}"
        )
        write(
            f"- **Internet reachable:** {_flag(evaluation.is_internet_reachable)}; "
            f"**likely exploitable:** {_flag(evaluation.is_likely_exploitable)}; "
            f"**PAIN:** {evaluation.pain.name}"
        )
        write(f"- **Potential agency impact:** {_cell(evaluation.potential_agency_impact)}")
        write(f"- **Rationale:** {_cell(evaluation.rationale)}")
        if evaluation.supplementary_risk_information is not None:
            write(
                "- **Supplementary risk information:** "
                f"{_cell(evaluation.supplementary_risk_information)}"
            )
        projection = evaluation.projected_next_reduction
        if projection is None:
            write("- **Projected next reduction:** none planned")
        else:
            write(
                f"- **Projected next reduction:** {projection.target_rating.name} by "
                f"{_iso(projection.estimated_at)}"
            )
        if evaluation.pain_reduction_events:
            reductions = ", ".join(
                f"{event.rating.name} at {_iso(event.reduced_at)}"
                for event in evaluation.pain_reduction_events
            )
            write(f"- **Completed PAIN reductions:** {reductions}")
        else:
            write("- **Completed PAIN reductions:** none recorded")

    disposition = _cell(_disposition_label(item))
    write(f"- **Disposition:** {disposition}; **remediated:** {_flag(item.remediated)}")
    if acceptance_rationale is not None:
        write(f"- **Acceptance rationale:** {_cell(acceptance_rationale)}")
    if item.is_overdue:
        write(f"- **Overdue:** {_cell(item.overdue_explanation)}")
    else:
        write("- **Overdue:** not overdue")
    write("")
    write("| Rule | Name | Force | Anchor | Start | Due | Satisfied |")
    write("|---|---|---|---|---|---|---|")
    for deadline in item.deadlines:
        write(
            "| "
            + " | ".join(
                (
                    _cell(deadline.rule_id),
                    _cell(deadline.rule_name),
                    _cell(deadline.force),
                    _cell(deadline.anchor),
                    _iso(deadline.start_at),
                    _iso(deadline.due_at),
                    _flag(deadline.satisfied),
                )
            )
            + " |"
        )
    write("")


_KEV_TAILS = {
    KevStatus.OPEN: "open",
    KevStatus.PAST_DUE: "past due",
    KevStatus.REMEDIATED: "stopped by remediation",
    KevStatus.FALSE_POSITIVE: "stopped as a false positive",
}


def _kev_line(kev: KevClock | None, as_of: datetime) -> str:
    """Render the Known exploited detail line: every matched entry, then the bound clock.

    An unmatched record names the date its lookup stopped at, which stays true for a CVE
    the catalog lists with a later `dateAdded`.
    """

    if kev is None:
        return (
            "no entry in the supplied CISA KEV catalog dated on or before "
            f"{as_of.astimezone(UTC).date().isoformat()}"
        )
    listed = ", ".join(
        f"{_cell(entry.cve_id)} (added {entry.date_added.isoformat()}, due "
        f"{entry.due_date.isoformat()}, ransomware use "
        f"{_cell(entry.known_ransomware_campaign_use or 'n/a')}, forensic triage "
        f"{_cell(entry.forensic_triage or 'n/a')})"
        for entry in kev.entries
    )
    bound = kev.bound
    verb = "ended" if kev.due_at <= as_of else "ends"
    if kev.status is KevStatus.ACCEPTED:
        tail = "accepted, past due" if kev.past_due else "accepted"
    else:
        tail = _KEV_TAILS[kev.status]
    return (
        f"{listed}; the clock follows {_cell(bound.cve_id)}, due date "
        f"{bound.due_date.isoformat()} {verb} {_iso(kev.due_at)}; {tail}"
    )


def _write_observation_ids(write: Callable[[str], None], item: CompiledVulnerability) -> None:
    """Name every observation grouped into one vulnerability, marking the untimed ones.

    The JSON extension carries `observationIds` and `untimestampedObservationIds`
    separately. Listing only the second here dropped, from the human rendering of a
    partly timestamped group, the very observation the detection time came from. The
    whole group is named in both branches; the label differs because a group where
    nothing carried a time is one statement rather than a list of exceptions.
    """

    untimestamped = frozenset(item.untimestamped_observation_ids)
    if untimestamped and untimestamped.issuperset(item.observation_ids):
        write(
            "- **Observations without a source timestamp:** "
            + ", ".join(_cell(value) for value in item.observation_ids)
        )
        return
    write(
        "- **Observations:** "
        + ", ".join(
            f"{_cell(value)} (no source timestamp)" if value in untimestamped else _cell(value)
            for value in item.observation_ids
        )
    )


def _flag(value: bool) -> str:
    return "yes" if value else "no"


def _cell(value: str) -> str:
    """Escape one Markdown table cell the way the compatibility renderer does."""

    return (
        value.replace("\\", "\\\\")
        .replace("|", "\\|")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("\r", " ")
        .replace("\n", " ")
    )


def _iso(value: datetime) -> str:
    return value.astimezone(UTC).isoformat().replace("+00:00", "Z")


def _require_aware(value: object, field_name: str) -> None:
    if not isinstance(value, datetime):
        raise TypeError(f"{field_name} must be a datetime, got {type(value).__name__}")
    if value.tzinfo is None or value.utcoffset() is None:
        raise ValueError(f"{field_name} must include a timezone")


def _require_absolute_http_uri(value: object) -> None:
    if not isinstance(value, str) or not value.strip():
        raise ValueError("package_uri must be non-blank text")
    parts = urlsplit(value)
    if parts.scheme not in {"http", "https"} or not parts.netloc:
        raise ValueError(f"package_uri must be an absolute http or https URI, got {value!r}")


