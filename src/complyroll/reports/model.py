@dataclass(frozen=True, slots=True)
class CompiledDeadline:
    """One policy clock computed for a vulnerability, with its provenance inputs."""

    rule_id: str
    rule_name: str
    force: str
    anchor: str
    start_at: datetime
    due_at: datetime
    timeframe_amount: int | str | None
    timeframe_unit: str | None
    satisfied: bool

    def to_dict(self) -> dict[str, Any]:
        # `satisfied` is the Markdown twin's Satisfied column. Publishing the clock
        # without it left a machine reader unable to tell a met deadline from a missed
        # one while a human reader of the same report could (ADR 0007 amendment, the
        # two renderings carry the same audit content). A clock with no structured
        # timeframe, such as the VDR-TFR-KEV one whose due date comes from the CISA
        # catalog, publishes a null timeframe (ADR 0012).
        timeframe = None
        if self.timeframe_amount is not None:
            timeframe = {"amount": self.timeframe_amount, "unit": self.timeframe_unit}
        return {
            "ruleId": self.rule_id,
            "ruleName": self.rule_name,
            "force": self.force,
            "anchor": self.anchor,
            "startAt": iso(self.start_at),
            "dueAt": iso(self.due_at),
            "satisfied": self.satisfied,
            "timeframe": timeframe,
        }


