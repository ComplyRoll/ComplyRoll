@dataclass(frozen=True, slots=True)
class CompiledVulnerability:
    """The normalized record both renderers read (README non-negotiable rule 5)."""

    tracking_id: str
    source_type: str
    source_record_id: str
    context_key: str
    description: str
    detected_at: datetime
    detected_at_source: str
    detection_source: str
    observation_ids: tuple[str, ...]
    resources: tuple[ResourceRef, ...]
    source_identifiers: tuple[str, ...]
    deadlines: tuple[CompiledDeadline, ...]
    is_overdue: bool
    overdue_explanation: str
    evaluation: EvaluationInput | None = None
    final_disposition: str | None = None
    remediated: bool = False
    status: CaseStatus | None = None
    untimestamped_observation_ids: tuple[str, ...] = ()
    original_tracking_id: str = ""

    @property
    def is_evaluated(self) -> bool:
        return self.evaluation is not None

    @property
    def has_disposition(self) -> bool:
        """Return True when a disposition of record exists for this vulnerability."""

        return self.final_disposition is not None or self.status is CaseStatus.ACCEPTED

    @property
    def activity_instants(self) -> tuple[datetime, ...]:
        """Return every recorded activity instant, for report-period selection.

        Detection, the completed evaluation, each completed PAIN reduction, and the
        projected next reduction are the recorded activity a period can contain
        (ADR 0007 amendment, report period selects contents).
        """

        instants = [self.detected_at]
        evaluation = self.evaluation
        if evaluation is not None:
            instants.append(evaluation.completed_at)
            instants.extend(event.reduced_at for event in evaluation.pain_reduction_events)
            if evaluation.projected_next_reduction is not None:
                instants.append(evaluation.projected_next_reduction.estimated_at)
        return tuple(instants)

    @property
    def evaluation_location(self) -> str:
        """Return the evaluations-file location behind this record, if any."""

        return self.evaluation.location if self.evaluation is not None else "no evaluation entry"

    @property
    def current_rating(self) -> PainRating | None:
        return self.evaluation.pain if self.evaluation is not None else None

    @property
    def next_due(self) -> CompiledDeadline | None:
        """Return the earliest deadline this vulnerability has not yet satisfied."""

        pending = [item for item in self.deadlines if not item.satisfied]
        if not pending:
            return None
        return min(pending, key=lambda item: (item.due_at, item.rule_id))

    def to_official_dict(self) -> dict[str, Any]:
        """Return the official `vulnerabilityDetail` object plus the extension."""

        value: dict[str, Any] = {
            "providerTrackingId": self.tracking_id,
            "detection": {
                "detectedAt": _iso(self.detected_at),
                "detectionSource": self.detection_source,
            },
            "vulnerabilityDescription": self.description,
            "overdueStatus": self._overdue_dict(),
            EXTENSION_KEY: self._extension_dict(),
        }
        evaluation = self.evaluation
        if evaluation is not None:
            value["evaluationCompletedAt"] = _iso(evaluation.completed_at)
            value["isInternetReachable"] = evaluation.is_internet_reachable
            value["isLikelyExploitable"] = evaluation.is_likely_exploitable
            value["currentRating"] = int(evaluation.pain)
            value["potentialAgencyImpact"] = evaluation.potential_agency_impact
            if evaluation.projected_next_reduction is not None:
                value["projectedNextReduction"] = {
                    "estimatedAt": _iso(evaluation.projected_next_reduction.estimated_at),
                    "targetRating": int(evaluation.projected_next_reduction.target_rating),
                }
            if evaluation.supplementary_risk_information is not None:
                value["supplementaryRiskInformation"] = (
                    evaluation.supplementary_risk_information
                )
            # Official since Common Definitions 0.3.0 (ADR 0009); the extension carried
            # this list while the report schemas had no slot for it.
            if evaluation.pain_reduction_events:
                value["painReductionEvents"] = [
                    {"reducedAt": _iso(event.reduced_at), "rating": int(event.rating)}
                    for event in evaluation.pain_reduction_events
                ]
        if self.final_disposition is not None:
            value["finalDisposition"] = self.final_disposition
        return value

    def _overdue_dict(self) -> dict[str, Any]:
        value: dict[str, Any] = {"isOverdue": self.is_overdue}
        if self.is_overdue:
            value["explanation"] = self.overdue_explanation
        return value

    def _extension_dict(self) -> dict[str, Any]:
        evaluation = self.evaluation
        return {
            "observationIds": list(self.observation_ids),
            "resources": [
                {"resourceId": item.resource_id, "resourceType": item.resource_type}
                for item in self.resources
            ],
            "sourceIdentifiers": list(self.source_identifiers),
            "untimestampedObservationIds": list(self.untimestamped_observation_ids),
            "deadlines": [item.to_dict() for item in self.deadlines],
            "remediated": self.remediated,
            "evaluator": evaluation.evaluator if evaluation else None,
            "rationale": evaluation.rationale if evaluation else None,
            "detectedAtSource": self.detected_at_source,
        }


