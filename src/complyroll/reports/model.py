class ReportCompileError(Exception):
    """Compilation stopped; no report was produced."""

    def __init__(self, diagnostics: Sequence[ReportDiagnostic]) -> None:
        self.diagnostics: tuple[ReportDiagnostic, ...] = tuple(diagnostics)
        summary = "; ".join(item.message for item in self.diagnostics[:3])
        suffix = "" if len(self.diagnostics) <= 3 else f"; plus {len(self.diagnostics) - 3} more"
        super().__init__(f"report compilation failed: {summary}{suffix}")


