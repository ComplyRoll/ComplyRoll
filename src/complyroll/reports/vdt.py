@dataclass(frozen=True, slots=True)
class ReportDiagnostic:
    """One machine-readable note about a compile run."""

    level: DiagnosticLevel
    code: str
    message: str
    location: str | None = None

    def render(self) -> str:
        """Return the single-line form used on stderr."""

        text = f"{self.level.value}: {self.code}: {self.message}"
        if self.location:
            text = f"{text} [{self.location}]"
        return text

    def to_dict(self) -> dict[str, str]:
        value = {"level": self.level.value, "code": self.code, "message": self.message}
        if self.location:
            value["location"] = self.location
        return value


class ReportCompileError(Exception):
    """Compilation stopped; no report was produced."""

    def __init__(self, diagnostics: Sequence[ReportDiagnostic]) -> None:
        self.diagnostics: tuple[ReportDiagnostic, ...] = tuple(diagnostics)
        summary = "; ".join(item.message for item in self.diagnostics[:3])
        suffix = "" if len(self.diagnostics) <= 3 else f"; plus {len(self.diagnostics) - 3} more"
        super().__init__(f"report compilation failed: {summary}{suffix}")


@dataclass(frozen=True, slots=True)
class ReportOptions:
    """Explicit package configuration for one compile run (Decision 5)."""

    certification_class: CertificationClass
    package_uri: str
    period_from: datetime
    period_to: datetime
    as_of: datetime
    calendar_timezone: str = "UTC"
    detected_at_attestation: datetime | None = None

    def __post_init__(self) -> None:
        if not isinstance(self.certification_class, CertificationClass):
            raise TypeError("certification_class must be a CertificationClass")
        _require_absolute_http_uri(self.package_uri)
        for value, name in (
            (self.period_from, "period_from"),
            (self.period_to, "period_to"),
            (self.as_of, "as_of"),
        ):
            _require_aware(value, name)
        if self.period_from > self.period_to:
            raise ValueError("period_from must not be after period_to")
        if self.detected_at_attestation is not None:
            _require_aware(self.detected_at_attestation, "detected_at_attestation")
        # Constructing the profile validates the calendar timezone at the boundary.
        CertificationProfile(
            self.certification_class,
            calendar_timezone=self.calendar_timezone,
        )

    @property
    def profile(self) -> CertificationProfile:
        """Return the certification profile these options select."""

        return CertificationProfile(
            self.certification_class,
            calendar_timezone=self.calendar_timezone,
        )


@dataclass(frozen=True, slots=True)
class CompiledDeadline:
    """One policy clock computed for a vulnerability, with its provenance inputs."""

    rule_id: str
    rule_name: str
    force: str
    anchor: str
    start_at: datetime
    due_at: datetime
    timeframe_amount: int | str
    timeframe_unit: str
    satisfied: bool

    def to_dict(self) -> dict[str, Any]:
        return {
            "ruleId": self.rule_id,
            "ruleName": self.rule_name,
            "force": self.force,
            "anchor": self.anchor,
            "startAt": _iso(self.start_at),
            "dueAt": _iso(self.due_at),
            "timeframe": {"amount": self.timeframe_amount, "unit": self.timeframe_unit},
        }


